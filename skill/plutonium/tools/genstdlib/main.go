// Command genstdlib writes the standard library reference of the Plutonium
// skill (references/stdlib*.md) from the sources under lib/pluto.
//
// Every package is loaded and type-checked with the compiler's own front
// end, so the listing is what `pluto doc` would show: the exported
// declarations of the hosted build, one line each, with the ownership kind
// of every type. Run it from the repository root after the library changes:
//
//	go run ./skill/plutonium/tools/genstdlib
//
// Flags: -lib is the library root (the directory that holds pluto/), -out the
// directory that receives the reference files.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"github.com/matjam/plutonium/internal/load"
	"github.com/matjam/plutonium/internal/syntax/ast"
	"github.com/matjam/plutonium/internal/syntax/format"
	"github.com/matjam/plutonium/internal/syntax/token"
	"github.com/matjam/plutonium/internal/types2"
)

// A group is one output file: a title, a short orientation, and the
// packages it lists.
type group struct {
	file, title, intro string
	pkgs               []string
}

var groups = []group{
	{
		"stdlib.md", "Standard library: text, errors and I/O",
		"Formatting, strings, numbers to text, errors, bytes and the io interfaces.",
		[]string{"fmt", "errors", "strings", "strconv", "unicode", "unicode/utf8", "bytes", "io"},
	},
	{
		"stdlib-os-time-math.md", "Standard library: files, flags, time, math and tests",
		"Files and processes, command-line flags, time, math, bit tricks and the test package.",
		[]string{"os", "os/exec", "path/filepath", "flag", "time", "math", "bits", "cmp", "testing"},
	},
	{
		"stdlib-memory-concurrency.md", "Standard library: memory, containers and concurrency",
		"Allocators, arenas, growable and fixed containers, sorting, iteration, tasks and locks.",
		[]string{
			"alloc", "alloc/debug", "arena", "vec", "hash", "container", "container/heap",
			"slices", "sort", "iter", "sync", "sync/atomic",
		},
	},
	{
		"stdlib-system.md", "Standard library: runtime, system calls and machine access",
		"The runtime that the compiler calls, Linux system calls and x86 instructions. Kernel and tool code only.",
		[]string{"rt", "syscall", "arch/x86"},
	},
}

func main() {
	lib := flag.String("lib", "lib", "library root (the directory that holds pluto/)")
	out := flag.String("out", "skill/plutonium/references", "output directory")
	flag.Parse()
	if err := run(*lib, *out); err != nil {
		fmt.Fprintln(os.Stderr, "genstdlib:", err)
		os.Exit(1)
	}
}

func run(lib, out string) error {
	fsys := os.DirFS(lib)
	have := map[string]bool{}
	err := fs.WalkDir(fsys, "pluto", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() && path.Base(p) == "internal" {
			return fs.SkipDir
		}
		if d.IsDir() && hasSource(fsys, p) {
			have[strings.TrimPrefix(p, "pluto/")] = true
		}
		return nil
	})
	if err != nil {
		return err
	}
	listed := map[string]bool{}
	for _, g := range groups {
		for _, p := range g.pkgs {
			listed[p] = true
			if !have[p] {
				return fmt.Errorf("package pluto/%s is listed but has no sources", p)
			}
		}
	}
	for p := range have {
		if !listed[p] {
			return fmt.Errorf("package pluto/%s is not in any group: add it to groups in genstdlib", p)
		}
	}
	cfg := &load.Config{
		Stdlib: fsys,
		Sizes:  types2.SizesFor("gc", "amd64"),
		Tags:   load.BuildTags(false, false, nil),
	}
	cfg.Tags["gencheck"] = true
	for i, g := range groups {
		var b bytes.Buffer
		fmt.Fprintf(&b, "# %s\n\n", g.title)
		fmt.Fprintf(&b, "<!-- Generated by skill/plutonium/tools/genstdlib from lib/pluto. Do not edit; regenerate. -->\n\n")
		fmt.Fprintf(&b, "%s\n\nListing of the hosted build (linux, amd64): every exported name, one line each, with the\n", g.intro)
		fmt.Fprintf(&b, "ownership kind of each type (`value`, `view`, `owner (moves)`, `counted`; see section 8.7). Methods are\n")
		fmt.Fprintf(&b, "indented under their type. For the full comment of a name run `pluto doc pluto/strings Cut` or\n")
		fmt.Fprintf(&b, "`pluto doc pluto/vec Vec.Push`. `(*T)` is a pointer receiver (borrows); `(T)` on an owner type\n")
		fmt.Fprintf(&b, "consumes the receiver.\n\n")
		if i == 0 {
			writeIndex(&b)
		}
		fmt.Fprintf(&b, "Packages in this file: %s.\n\n", strings.Join(quoted(g.pkgs), ", "))
		for _, p := range g.pkgs {
			if err := writePackage(&b, cfg, p); err != nil {
				return err
			}
		}
		if err := os.WriteFile(filepath.Join(out, g.file), b.Bytes(), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func quoted(ss []string) []string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = "`pluto/" + s + "`"
	}
	return out
}

func hasSource(fsys fs.FS, dir string) bool {
	entries, err := fs.ReadDir(fsys, dir)
	if err != nil {
		return false
	}
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".p") && !strings.HasSuffix(e.Name(), "_test.p") {
			return true
		}
	}
	return false
}

// writeIndex writes the table that says where each package is listed.
func writeIndex(b *bytes.Buffer) {
	fmt.Fprintf(b, "## Where each package is listed\n\n| File | Packages |\n|---|---|\n")
	for _, g := range groups {
		fmt.Fprintf(b, "| `%s` | %s |\n", g.file, strings.Join(quoted(g.pkgs), ", "))
	}
	fmt.Fprintf(b, "\nThe library has no `net`, `http`, `json`, `regexp`, `log`, `bufio`, `reflect`, `encoding/...`,\n")
	fmt.Fprintf(b, "`context` or `text/template`. Check a name here before you use it.\n\n")
}

// An item is one exported declaration to list.
type item struct {
	name string
	kind string // "func", "type"
	line string
	doc  string
}

func writePackage(b *bytes.Buffer, cfg *load.Config, name string) error {
	prog, err := load.LoadPackage(cfg, "pluto/"+name)
	if err != nil {
		return fmt.Errorf("pluto/%s: %v", name, err)
	}
	p := prog.Main
	fmt.Fprintf(b, "## pluto/%s\n\n", name)
	if doc := packageDoc(p); doc != "" {
		fmt.Fprintf(b, "%s\n\n", doc)
	}
	fmt.Fprintf(b, "```\n")
	qf := func(other *types2.Package) string {
		if other == p.Types {
			return ""
		}
		return other.Name()
	}
	var types, funcs []item
	consts := map[string][]string{}
	var constOrder []string
	var vars []string
	methods := map[string][]item{}
	for _, f := range p.Files {
		for _, decl := range f.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if !ast.IsExported(d.Name.Name) {
					continue
				}
				cp := *d
				cp.Body, cp.Doc = nil, nil
				line := oneLine(prog.Fset, &cp)
				if d.Recv == nil {
					funcs = append(funcs, item{name: d.Name.Name, kind: "func", line: line, doc: sentence(d.Doc)})
					continue
				}
				recv := recvBase(d.Recv)
				if !ast.IsExported(recv) {
					continue
				}
				methods[recv] = append(methods[recv], item{name: d.Name.Name, kind: "func", line: line})
			case *ast.GenDecl:
				for _, spec := range d.Specs {
					switch s := spec.(type) {
					case *ast.TypeSpec:
						if !ast.IsExported(s.Name.Name) {
							continue
						}
						obj := p.Info.Defs[s.Name]
						kind := fmt.Sprint(types2.KindOf(obj.Type()))
						doc := sentence(firstDoc(s.Doc, d.Doc))
						types = append(types, item{name: s.Name.Name, kind: "type", line: typeLine(prog.Fset, s, kind), doc: doc})
					case *ast.ValueSpec:
						for _, n := range s.Names {
							if !ast.IsExported(n.Name) {
								continue
							}
							obj := p.Info.Defs[n]
							switch o := obj.(type) {
							case *types2.Const:
								key := ""
								if bt, ok := o.Type().(*types2.Basic); !ok || bt.Info()&types2.IsUntyped == 0 {
									key = types2.TypeString(o.Type(), qf)
								}
								if _, ok := consts[key]; !ok {
									constOrder = append(constOrder, key)
								}
								consts[key] = append(consts[key], n.Name)
							case *types2.Var:
								vars = append(vars, n.Name+" "+types2.TypeString(o.Type(), qf))
							}
						}
					}
				}
			}
		}
	}
	sort.Slice(types, func(i, j int) bool { return types[i].name < types[j].name })
	sort.Slice(funcs, func(i, j int) bool { return funcs[i].name < funcs[j].name })
	for _, key := range constOrder {
		names := consts[key]
		sort.Strings(names)
		label := "const:"
		if key != "" {
			label = "const " + key + ":"
		}
		writeWrapped(b, label, names)
	}
	sort.Strings(vars)
	if len(vars) > 0 {
		writeWrapped(b, "var:", vars)
	}
	for _, t := range types {
		fmt.Fprintf(b, "%s", t.line)
		if t.doc != "" {
			fmt.Fprintf(b, "\n  // %s", t.doc)
		}
		fmt.Fprintf(b, "\n")
		ms := methods[t.name]
		ms = append(ms, promoted(p, t.name, ms, qf)...)
		sort.Slice(ms, func(i, j int) bool { return ms[i].name < ms[j].name })
		for _, m := range ms {
			fmt.Fprintf(b, "  %s\n", m.line)
		}
	}
	for _, f := range funcs {
		fmt.Fprintf(b, "%s\n", f.line)
	}
	fmt.Fprintf(b, "```\n\n")
	return nil
}

// promoted returns the exported methods of *T that T gets from an embedded
// field, which have no declaration on T itself.
func promoted(p *load.Package, name string, declared []item, qf types2.Qualifier) []item {
	obj, ok := p.Types.Scope().Lookup(name).(*types2.TypeName)
	if !ok {
		return nil
	}
	t := types2.Unalias(obj.Type())
	if types2.IsInterface(t) {
		return nil
	}
	have := map[string]bool{}
	for _, d := range declared {
		have[d.name] = true
	}
	set := types2.NewMethodSet(types2.NewPointer(t))
	var out []item
	for i := range set.Len() {
		fn, ok := set.At(i).Obj().(*types2.Func)
		if !ok || !ast.IsExported(fn.Name()) || have[fn.Name()] {
			continue
		}
		sig := strings.TrimPrefix(types2.TypeString(fn.Type(), qf), "func")
		out = append(out, item{name: fn.Name(), kind: "func", line: fmt.Sprintf("func (*%s) %s%s  // promoted", name, fn.Name(), sig)})
	}
	return out
}

// writeWrapped writes a label and a list of names, wrapped at 100 columns.
func writeWrapped(b *bytes.Buffer, label string, names []string) {
	line := label
	for i, n := range names {
		sep := ", "
		if i == 0 {
			sep = " "
		}
		if len(line)+len(sep)+len(n) > 100 {
			fmt.Fprintf(b, "%s,\n", strings.TrimRight(line, " "))
			line = "  " + n
			continue
		}
		line += sep + n
	}
	fmt.Fprintf(b, "%s\n", line)
}

func packageDoc(p *load.Package) string {
	for _, f := range p.Files {
		if text := strings.TrimSpace(f.Doc.Text()); text != "" {
			paras := strings.Split(text, "\n\n")
			first := strings.Join(strings.Fields(paras[0]), " ")
			return sentences(first, 3)
		}
	}
	return ""
}

// sentences returns the first n sentences of s.
func sentences(s string, n int) string {
	out := ""
	for i := 0; i < n; i++ {
		j := strings.Index(s, ". ")
		if j < 0 {
			return out + s
		}
		out += s[:j+2]
		s = s[j+2:]
	}
	return strings.TrimSpace(out)
}

func firstDoc(groups ...*ast.CommentGroup) *ast.CommentGroup {
	for _, g := range groups {
		if g != nil {
			return g
		}
	}
	return nil
}

// sentence returns the first sentence of a comment, trimmed to one line.
func sentence(g *ast.CommentGroup) string {
	if g == nil {
		return ""
	}
	text := strings.Join(strings.Fields(g.Text()), " ")
	if strings.HasPrefix(text, "//pu:") {
		return ""
	}
	if i := strings.Index(text, ". "); i >= 0 {
		text = text[:i+1]
	}
	if len(text) > 130 {
		text = text[:127] + "..."
	}
	return text
}

func recvBase(recv *ast.FieldList) string {
	if recv == nil || len(recv.List) == 0 {
		return ""
	}
	t := recv.List[0].Type
	for {
		switch x := t.(type) {
		case *ast.StarExpr:
			t = x.X
		case *ast.ParenExpr:
			t = x.X
		case *ast.IndexExpr:
			t = x.X
		case *ast.IndexListExpr:
			t = x.X
		case *ast.Ident:
			return x.Name
		default:
			return ""
		}
	}
}

// oneLine formats a node on one line.
func oneLine(fset *token.FileSet, n ast.Node) string {
	var b bytes.Buffer
	if err := format.Node(&b, fset, n); err != nil {
		return fmt.Sprintf("// format error: %v", err)
	}
	return collapse(b.String())
}

// collapse joins the lines of formatted source into one line.
func collapse(s string) string {
	var parts []string
	for _, l := range strings.Split(s, "\n") {
		l = strings.TrimSpace(l)
		if l == "" || strings.HasPrefix(l, "//") {
			continue
		}
		parts = append(parts, l)
	}
	out := ""
	for i, part := range parts {
		switch {
		case i == 0:
		case strings.HasSuffix(parts[i-1], "|") || strings.HasSuffix(parts[i-1], ","):
			out += " "
		default:
			out += "; "
		}
		out += part
	}
	for _, r := range [][2]string{{"{; ", "{ "}, {"; }", " }"}, {"(; ", "("}, {"; )", ")"}, {",; ", ", "}} {
		out = strings.ReplaceAll(out, r[0], r[1])
	}
	return out
}

// typeLine renders a type declaration with its kind, leaving out the
// unexported fields of a struct.
func typeLine(fset *token.FileSet, s *ast.TypeSpec, kind string) string {
	cp := *s
	cp.Doc, cp.Comment = nil, nil
	cp.Type = filterType(cp.Type)
	decl := &ast.GenDecl{Tok: token.TYPE, Specs: []ast.Spec{&cp}}
	return oneLine(fset, decl) + "  [" + kind + "]"
}

func filterType(e ast.Expr) ast.Expr {
	switch t := e.(type) {
	case *ast.StructType:
		cp := *t
		fl := *t.Fields
		fl.List = nil
		hidden := false
		for _, f := range t.Fields.List {
			g := *f
			g.Doc, g.Comment, g.Tag = nil, nil, nil
			if len(g.Names) == 0 {
				if n := embeddedName(g.Type); ast.IsExported(n) {
					fl.List = append(fl.List, &g)
				} else {
					hidden = true
				}
				continue
			}
			var names []*ast.Ident
			for _, n := range g.Names {
				if ast.IsExported(n.Name) {
					names = append(names, n)
				} else {
					hidden = true
				}
			}
			if len(names) > 0 {
				g.Names = names
				fl.List = append(fl.List, &g)
			}
		}
		if hidden {
			fl.List = append(fl.List, &ast.Field{Names: []*ast.Ident{{Name: "_"}}, Type: &ast.Ident{Name: "unexported"}})
		}
		cp.Fields = &fl
		return &cp
	case *ast.InterfaceType:
		cp := *t
		ml := *t.Methods
		ml.List = nil
		for _, f := range t.Methods.List {
			g := *f
			g.Doc, g.Comment = nil, nil
			ml.List = append(ml.List, &g)
		}
		cp.Methods = &ml
		return &cp
	}
	return e
}

func embeddedName(e ast.Expr) string {
	switch x := e.(type) {
	case *ast.StarExpr:
		return embeddedName(x.X)
	case *ast.Ident:
		return x.Name
	case *ast.SelectorExpr:
		return x.Sel.Name
	case *ast.IndexExpr:
		return embeddedName(x.X)
	case *ast.IndexListExpr:
		return embeddedName(x.X)
	}
	return ""
}
