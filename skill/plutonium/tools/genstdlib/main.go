// Command genstdlib writes the standard library reference of the Plutonium
// skill (references/stdlib*.md) from the sources under lib/pluto.
//
// The listing comes from the pluto binary's doc command, which loads and
// type-checks every package with the compiler's own front end: the exported
// declarations of the hosted build, one line each, with the ownership kind
// of every type. Run it from the repository root after the library changes,
// with pluto on PATH or named by -pluto:
//
//	go run ./skill/plutonium/tools/genstdlib
//
// Flags: -pluto is the compiler binary, -lib the library root (the directory
// that holds pluto/, passed to the compiler as PLUTOROOT), -out the directory
// that receives the reference files.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// A group is one output file: a title, a short orientation, and the
// packages it lists.
type group struct {
	file, title, intro string
	pkgs               []string
}

var groups = []group{
	{
		"stdlib.md", "Standard library: text, errors and I/O",
		"Formatting, strings, numbers to text, errors, bytes and the io interfaces.",
		[]string{"fmt", "errors", "strings", "strconv", "unicode", "unicode/utf8", "bytes", "io"},
	},
	{
		"stdlib-os-time-math.md", "Standard library: files, flags, time, math and tests",
		"Files and processes, command-line flags, time, math, bit tricks and the test package.",
		[]string{"os", "os/exec", "path/filepath", "flag", "time", "math", "bits", "cmp", "testing"},
	},
	{
		"stdlib-memory-concurrency.md", "Standard library: memory, containers and concurrency",
		"Allocators, arenas, growable and fixed containers, sorting, iteration, tasks and locks.",
		[]string{
			"alloc", "alloc/debug", "arena", "vec", "hash", "container", "container/heap",
			"slices", "sort", "iter", "sync", "sync/atomic",
		},
	},
	{
		"stdlib-system.md", "Standard library: runtime, system calls and machine access",
		"The runtime that the compiler calls, Linux system calls and x86 instructions. Kernel and tool code only.",
		[]string{"rt", "syscall", "arch/x86"},
	},
}

func main() {
	pluto := flag.String("pluto", "pluto", "the pluto compiler binary")
	lib := flag.String("lib", "lib", "library root (the directory that holds pluto/)")
	out := flag.String("out", "skill/plutonium/references", "output directory")
	flag.Parse()
	if err := run(*pluto, *lib, *out); err != nil {
		fmt.Fprintln(os.Stderr, "genstdlib:", err)
		os.Exit(1)
	}
}

// A gen runs the compiler against one library root.
type gen struct {
	pluto string
	env   []string
	lib   fs.FS
}

func run(pluto, lib, out string) error {
	bin, err := exec.LookPath(pluto)
	if err != nil {
		return fmt.Errorf("no pluto compiler (%v): put pluto on PATH or name it with -pluto", err)
	}
	root, err := filepath.Abs(lib)
	if err != nil {
		return err
	}
	g := &gen{pluto: bin, env: append(os.Environ(), "PLUTOROOT="+root), lib: os.DirFS(root)}
	have := map[string]bool{}
	err = fs.WalkDir(g.lib, "pluto", func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() && path.Base(p) == "internal" {
			return fs.SkipDir
		}
		if d.IsDir() && hasSource(g.lib, p) {
			have[strings.TrimPrefix(p, "pluto/")] = true
		}
		return nil
	})
	if err != nil {
		return err
	}
	listed := map[string]bool{}
	for _, gr := range groups {
		for _, p := range gr.pkgs {
			listed[p] = true
			if !have[p] {
				return fmt.Errorf("package pluto/%s is listed but has no sources", p)
			}
		}
	}
	for p := range have {
		if !listed[p] {
			return fmt.Errorf("package pluto/%s is not in any group: add it to groups in genstdlib", p)
		}
	}
	for i, gr := range groups {
		var b bytes.Buffer
		fmt.Fprintf(&b, "# %s\n\n", gr.title)
		fmt.Fprintf(&b, "<!-- Generated by skill/plutonium/tools/genstdlib from lib/pluto. Do not edit; regenerate. -->\n\n")
		fmt.Fprintf(&b, "%s\n\nListing of the hosted build (linux, amd64): every exported name, one line each, with the\n", gr.intro)
		fmt.Fprintf(&b, "ownership kind of each type (`value`, `view`, `owner (moves)`, `counted`; see section 8.7). Methods are\n")
		fmt.Fprintf(&b, "indented under their type. For the full comment of a name run `pluto doc pluto/strings Cut` or\n")
		fmt.Fprintf(&b, "`pluto doc pluto/vec Vec.Push`. `(*T)` is a pointer receiver (borrows); `(T)` on an owner type\n")
		fmt.Fprintf(&b, "consumes the receiver.\n\n")
		if i == 0 {
			writeIndex(&b)
		}
		fmt.Fprintf(&b, "Packages in this file: %s.\n\n", strings.Join(quoted(gr.pkgs), ", "))
		for _, p := range gr.pkgs {
			if err := g.writePackage(&b, p); err != nil {
				return fmt.Errorf("pluto/%s: %v", p, err)
			}
		}
		if err := os.WriteFile(filepath.Join(out, gr.file), b.Bytes(), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func quoted(ss []string) []string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = "`pluto/" + s + "`"
	}
	return out
}

func hasSource(fsys fs.FS, dir string) bool {
	entries, err := fs.ReadDir(fsys, dir)
	if err != nil {
		return false
	}
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".p") && !strings.HasSuffix(e.Name(), "_test.p") {
			return true
		}
	}
	return false
}

// writeIndex writes the table that says where each package is listed.
func writeIndex(b *bytes.Buffer) {
	fmt.Fprintf(b, "## Where each package is listed\n\n| File | Packages |\n|---|---|\n")
	for _, gr := range groups {
		fmt.Fprintf(b, "| `%s` | %s |\n", gr.file, strings.Join(quoted(gr.pkgs), ", "))
	}
	fmt.Fprintf(b, "\nThe library has no `net`, `http`, `json`, `regexp`, `log`, `bufio`, `reflect`, `encoding/...`,\n")
	fmt.Fprintf(b, "`context` or `text/template`. Check a name here before you use it.\n\n")
}

// command runs pluto with args and stdin and returns its standard output.
func (g *gen) command(stdin string, args ...string) (string, error) {
	cmd := exec.Command(g.pluto, args...)
	cmd.Env = g.env
	cmd.Stdin = strings.NewReader(stdin)
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	if err := cmd.Run(); err != nil {
		return "", fmt.Errorf("pluto %s: %v\n%s", strings.Join(args, " "), err, stderr.String())
	}
	return stdout.String(), nil
}

// A docEntry is one declaration in the output of pluto doc.
type docEntry struct {
	source    string   // "Source:" line: where a promoted method is declared
	kind      string   // ownership kind of a type
	decl      []string // the declaration, as format prints it
	signature string   // "Signature:" line
	comment   []string // the doc comment, one entry per line
}

// name returns the declared name: the function or method name, or the
// first name after const, var or type.
func (e *docEntry) name() string {
	line := e.decl[0]
	if rest, ok := strings.CutPrefix(line, "func ("); ok {
		line = "func " + rest[closing(rest, '(', ')')+1:]
	}
	f := strings.FieldsFunc(line, func(r rune) bool { return !isIdent(r) })
	if len(f) < 2 {
		return ""
	}
	return f[1]
}

// method reports whether the entry is a method declaration.
func (e *docEntry) method() bool { return strings.HasPrefix(e.decl[0], "func (") }

// receiver returns the base type name of a method's receiver as spelled in
// its declaration: Vec for func (v *Vec[T]) Push(x T).
func (e *docEntry) receiver() string {
	rest := strings.TrimPrefix(e.decl[0], "func (")
	r := rest[:closing(rest, '(', ')')]
	if s, b := strings.IndexByte(r, ' '), strings.IndexByte(r, '['); s >= 0 && (b < 0 || s < b) {
		r = r[s+1:]
	}
	r = strings.TrimLeft(r, "*(")
	if i := strings.IndexAny(r, "[)"); i >= 0 {
		r = r[:i]
	}
	return r
}

// closing returns the index of the bracket that closes an opening bracket
// just before s.
func closing(s string, open, close byte) int {
	depth := 1
	for i := 0; i < len(s); i++ {
		switch s[i] {
		case open:
			depth++
		case close:
			depth--
			if depth == 0 {
				return i
			}
		}
	}
	return len(s)
}

func isIdent(r rune) bool {
	return r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r >= 0x80
}

func exported(name string) bool { return name != "" && name[0] >= 'A' && name[0] <= 'Z' }

var (
	kindLine  = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]* \[[a-z ()]+\]$`)
	declStart = regexp.MustCompile(`^(func [(A-Za-z_]|type [A-Za-z_]|const [A-Za-z_]|var [A-Za-z_])`)
)

// entryStart reports whether line opens an entry of pluto doc's output.
func entryStart(line string) bool {
	return strings.HasPrefix(line, "Source: ") || kindLine.MatchString(line) || declStart.MatchString(line)
}

// parseDoc splits the output of pluto doc into the package comment, as
// lines, and its entries.
func parseDoc(out string) ([]string, []*docEntry, error) {
	lines := strings.Split(strings.TrimSuffix(out, "\n"), "\n")
	if len(lines) == 0 || !strings.HasPrefix(lines[0], "package ") {
		return nil, nil, fmt.Errorf("pluto doc printed no package header")
	}
	i := 1
	var pkgDoc []string
	for i < len(lines) && !(lines[i-1] == "" && entryStart(lines[i])) {
		pkgDoc = append(pkgDoc, lines[i])
		i++
	}
	var entries []*docEntry
	for i < len(lines) {
		e := &docEntry{}
		if s, ok := strings.CutPrefix(lines[i], "Source: "); ok {
			e.source = s
			i++
		}
		if i < len(lines) && kindLine.MatchString(lines[i]) {
			_, k, _ := strings.Cut(lines[i], " [")
			e.kind = strings.TrimSuffix(k, "]")
			i++
		}
		if i >= len(lines) || !declStart.MatchString(lines[i]) {
			return nil, nil, fmt.Errorf("pluto doc: no declaration at line %d: %q", i+1, lines[min(i, len(lines)-1)])
		}
		e.decl = append(e.decl, lines[i])
		// The declaration goes on to its closing bracket; a blank line inside
		// it is followed by an indented one.
		for i++; i < len(lines); i++ {
			l := lines[i]
			if l == "" && (i+1 >= len(lines) || !strings.HasPrefix(lines[i+1], "\t")) ||
				strings.HasPrefix(l, "    ") || strings.HasPrefix(l, "Signature: ") {
				break
			}
			e.decl = append(e.decl, l)
		}
		if i < len(lines) {
			if s, ok := strings.CutPrefix(lines[i], "Signature: "); ok {
				e.signature = s
				i++
			}
		}
		for ; i < len(lines) && lines[i] != ""; i++ {
			c, ok := strings.CutPrefix(lines[i], "    ")
			if !ok {
				return nil, nil, fmt.Errorf("pluto doc: unexpected line %d: %q", i+1, lines[i])
			}
			e.comment = append(e.comment, c)
		}
		entries = append(entries, e)
		if i < len(lines) {
			i++ // the blank line between entries
		}
	}
	return pkgDoc, entries, nil
}

// An item is one exported declaration to list.
type item struct {
	name string
	line string
	doc  string
}

func (g *gen) writePackage(b *bytes.Buffer, name string) error {
	out, err := g.command("", "doc", "-all", "pluto/"+name)
	if err != nil {
		return err
	}
	pkgDoc, entries, err := parseDoc(out)
	if err != nil {
		return err
	}
	fmt.Fprintf(b, "## pluto/%s\n\n", name)
	if doc := packageDoc(pkgDoc); doc != "" {
		fmt.Fprintf(b, "%s\n\n", doc)
	}
	fmt.Fprintf(b, "```\n")
	var types []*docEntry
	var funcs []item
	consts := map[string][]string{}
	var vars []string
	methods := map[string][]item{}
	for _, e := range entries {
		n := e.name()
		if !exported(n) {
			continue
		}
		switch {
		case e.method():
			if recv := e.receiver(); exported(recv) {
				methods[recv] = append(methods[recv], item{name: n, line: collapse(strings.Join(e.decl, "\n"))})
			}
		case strings.HasPrefix(e.decl[0], "func "):
			funcs = append(funcs, item{name: n, line: collapse(strings.Join(e.decl, "\n"))})
		case strings.HasPrefix(e.decl[0], "type "):
			types = append(types, e)
		case strings.HasPrefix(e.decl[0], "const "):
			// const X = 1 is untyped, const X T = 1 has type T.
			d := strings.TrimPrefix(e.decl[0], "const "+n+" ")
			key := ""
			if t, _, ok := strings.Cut(d, " = "); ok && !strings.HasPrefix(d, "= ") {
				key = t
			}
			consts[key] = append(consts[key], n)
		case strings.HasPrefix(e.decl[0], "var "):
			vars = append(vars, strings.TrimPrefix(e.decl[0], "var "))
		}
	}
	constOrder, err := g.constOrder(name, consts)
	if err != nil {
		return err
	}
	for _, key := range constOrder {
		names := consts[key]
		sort.Strings(names)
		label := "const:"
		if key != "" {
			label = "const " + key + ":"
		}
		writeWrapped(b, label, names)
	}
	sort.Strings(vars)
	if len(vars) > 0 {
		writeWrapped(b, "var:", vars)
	}
	lines, err := g.typeLines(types)
	if err != nil {
		return err
	}
	sort.Slice(types, func(i, j int) bool { return types[i].name() < types[j].name() })
	for _, t := range types {
		tn := t.name()
		fmt.Fprintf(b, "%s", lines[t])
		if doc := sentence(t.comment); doc != "" {
			fmt.Fprintf(b, "\n  // %s", doc)
		}
		fmt.Fprintf(b, "\n")
		ms := methods[tn]
		prom, err := g.promoted(name, t, ms)
		if err != nil {
			return err
		}
		ms = append(ms, prom...)
		sort.Slice(ms, func(i, j int) bool { return ms[i].name < ms[j].name })
		for _, m := range ms {
			fmt.Fprintf(b, "  %s\n", m.line)
		}
	}
	sort.Slice(funcs, func(i, j int) bool { return funcs[i].name < funcs[j].name })
	for _, f := range funcs {
		fmt.Fprintf(b, "%s\n", f.line)
	}
	fmt.Fprintf(b, "```\n\n")
	return nil
}

// constOrder returns the keys of consts (the type of a group of constants,
// "" for untyped ones) in the order their first constant is declared in the
// package's sources. pluto doc lists names sorted, so the order comes from
// the .p files, read in name order as the loader reads them.
func (g *gen) constOrder(pkg string, consts map[string][]string) ([]string, error) {
	if len(consts) < 2 {
		var keys []string
		for k := range consts {
			keys = append(keys, k)
		}
		return keys, nil
	}
	keyOf := map[string]string{}
	for k, names := range consts {
		for _, n := range names {
			keyOf[n] = k
		}
	}
	dir := "pluto/" + pkg
	files, err := fs.ReadDir(g.lib, dir)
	if err != nil {
		return nil, err
	}
	seen := map[string]bool{}
	var order []string
	for _, f := range files {
		if f.IsDir() || !strings.HasSuffix(f.Name(), ".p") || strings.HasSuffix(f.Name(), "_test.p") {
			continue
		}
		src, err := fs.ReadFile(g.lib, dir+"/"+f.Name())
		if err != nil {
			return nil, err
		}
		for _, n := range constNames(string(src)) {
			if k, ok := keyOf[n]; ok && !seen[k] {
				seen[k] = true
				order = append(order, k)
			}
		}
	}
	if len(order) != len(consts) {
		return nil, fmt.Errorf("found the declarations of %d of %d constant groups in the sources", len(order), len(consts))
	}
	return order, nil
}

var constSpec = regexp.MustCompile(`^\s*([A-Za-z_][A-Za-z0-9_]*(?:\s*,\s*[A-Za-z_][A-Za-z0-9_]*)*)`)

// constNames returns the names of the top-level constants that src declares,
// in source order.
func constNames(src string) []string {
	var names []string
	add := func(spec string) {
		if m := constSpec.FindStringSubmatch(spec); m != nil {
			for _, n := range strings.Split(m[1], ",") {
				names = append(names, strings.TrimSpace(n))
			}
		}
	}
	inBlock := false
	for _, line := range strings.Split(src, "\n") {
		switch {
		case inBlock && strings.HasPrefix(line, ")"):
			inBlock = false
		case inBlock:
			// A spec of the block: one tab of indentation.
			if strings.HasPrefix(line, "\t") && !strings.HasPrefix(line, "\t\t") && !strings.HasPrefix(line, "\t//") {
				add(line)
			}
		case strings.HasPrefix(line, "const ("):
			inBlock = true
		case strings.HasPrefix(line, "const "):
			add(strings.TrimPrefix(line, "const "))
		}
	}
	return names
}

// promoted returns the exported methods of *T that T gets from an embedded
// field, which have no declaration on T itself. pluto doc pkg T lists the
// method set of *T; the methods it lists that declared does not are the
// promoted ones.
func (g *gen) promoted(pkg string, t *docEntry, declared []item) ([]item, error) {
	if strings.HasSuffix(t.decl[0], "interface {") || strings.HasSuffix(t.decl[0], "interface{}") {
		return nil, nil
	}
	name := t.name()
	out, err := g.command("", "doc", "pluto/"+pkg, name)
	if err != nil {
		return nil, err
	}
	_, entries, err := parseDoc(out)
	if err != nil {
		return nil, err
	}
	have := map[string]bool{}
	for _, d := range declared {
		have[d.name] = true
	}
	var items []item
	for _, e := range entries {
		n := e.name()
		// A method with no Source line is declared on T itself, or is a
		// method of an interface, which has no declaration.
		if !e.method() || !exported(n) || have[n] || e.source == "" {
			continue
		}
		sig := ""
		if e.signature != "" {
			// func (T).Name(params) results
			_, sig, _ = strings.Cut(e.signature, ")."+n)
		} else {
			if src, _, _ := strings.Cut(e.source, "."); src != "pluto/"+pkg {
				return nil, fmt.Errorf("%s.%s is promoted from package %s: genstdlib cannot qualify its signature", name, n, src)
			}
			decl := collapse(strings.Join(e.decl, "\n"))
			rest := strings.TrimPrefix(decl, "func (")
			rest = strings.TrimPrefix(rest[closing(rest, '(', ')')+1:], " "+n)
			sig = typeSignature(rest)
		}
		items = append(items, item{name: n, line: fmt.Sprintf("func (*%s) %s%s  // promoted", name, n, sig)})
	}
	return items, nil
}

// typeSignature rewrites the parameters and results of a declaration as a
// signature type prints them: a, b int becomes a int, b int.
func typeSignature(s string) string {
	params := s[1:]
	end := closing(params, '(', ')')
	out := "(" + expandFields(params[:end]) + ")"
	results := strings.TrimSpace(params[end+1:])
	if strings.HasPrefix(results, "(") {
		r := results[1:]
		results = "(" + expandFields(r[:closing(r, '(', ')')]) + ")"
	}
	if results != "" {
		out += " " + results
	}
	return out
}

// expandFields gives every name in a parameter list its own type.
func expandFields(list string) string {
	var fields []string
	depth, start := 0, 0
	for i := 0; i < len(list); i++ {
		switch list[i] {
		case '(', '[', '{':
			depth++
		case ')', ']', '}':
			depth--
		case ',':
			if depth == 0 {
				fields = append(fields, strings.TrimSpace(list[start:i]))
				start = i + 1
			}
		}
	}
	if s := strings.TrimSpace(list[start:]); s != "" {
		fields = append(fields, s)
	}
	named := false
	for _, f := range fields {
		if n, _, ok := strings.Cut(f, " "); ok && !keyword[n] && !strings.ContainsAny(n, ".*[]") {
			named = true
		}
	}
	if !named {
		return strings.Join(fields, ", ")
	}
	var pending []string
	var out []string
	for _, f := range fields {
		n, typ, ok := strings.Cut(f, " ")
		if !ok {
			pending = append(pending, f)
			continue
		}
		for _, p := range pending {
			out = append(out, p+" "+typ)
		}
		pending = nil
		out = append(out, n+" "+typ)
	}
	return strings.Join(out, ", ")
}

var keyword = map[string]bool{"chan": true, "func": true, "map": true, "struct": true, "interface": true}

// writeWrapped writes a label and a list of names, wrapped at 100 columns.
func writeWrapped(b *bytes.Buffer, label string, names []string) {
	line := label
	for i, n := range names {
		sep := ", "
		if i == 0 {
			sep = " "
		}
		if len(line)+len(sep)+len(n) > 100 {
			fmt.Fprintf(b, "%s,\n", strings.TrimRight(line, " "))
			line = "  " + n
			continue
		}
		line += sep + n
	}
	fmt.Fprintf(b, "%s\n", line)
}

// packageDoc returns the first sentences of the package comment that pluto
// doc printed: the comment of the first file that has one.
func packageDoc(lines []string) string {
	for len(lines) > 0 && lines[0] == "" {
		lines = lines[1:]
	}
	var para []string
	for _, l := range lines {
		if strings.TrimSpace(l) == "" {
			break
		}
		para = append(para, l)
	}
	first := strings.Join(strings.Fields(strings.Join(para, "\n")), " ")
	return sentences(first, 3)
}

// sentences returns the first n sentences of s.
func sentences(s string, n int) string {
	out := ""
	for i := 0; i < n; i++ {
		j := strings.Index(s, ". ")
		if j < 0 {
			return out + s
		}
		out += s[:j+2]
		s = s[j+2:]
	}
	return strings.TrimSpace(out)
}

// sentence returns the first sentence of a comment, trimmed to one line.
func sentence(comment []string) string {
	text := strings.Join(strings.Fields(strings.Join(comment, "\n")), " ")
	if text == "" || strings.HasPrefix(text, "//pu:") {
		return ""
	}
	if i := strings.Index(text, ". "); i >= 0 {
		text = text[:i+1]
	}
	if len(text) > 130 {
		text = text[:127] + "..."
	}
	return text
}

// collapse joins the lines of formatted source into one line.
func collapse(s string) string {
	var parts []string
	for _, l := range strings.Split(s, "\n") {
		l = strings.TrimSpace(l)
		if l == "" || strings.HasPrefix(l, "//") {
			continue
		}
		parts = append(parts, l)
	}
	out := ""
	for i, part := range parts {
		switch {
		case i == 0:
		case strings.HasSuffix(parts[i-1], "|") || strings.HasSuffix(parts[i-1], ","):
			out += " "
		default:
			out += "; "
		}
		out += part
	}
	for _, r := range [][2]string{{"{; ", "{ "}, {"; }", " }"}, {"(; ", "("}, {"; )", ")"}, {",; ", ", "}} {
		out = strings.ReplaceAll(out, r[0], r[1])
	}
	return out
}

// typeLines renders each type declaration on one line with its kind,
// leaving out the unexported fields of a struct and the comments of its
// fields and of an interface's methods. The edited declarations go through
// pluto fmt together, so that field alignment is computed as the formatter
// computes it for the fields that remain.
func (g *gen) typeLines(types []*docEntry) (map[*docEntry]string, error) {
	var src strings.Builder
	src.WriteString("package p\n")
	for _, t := range types {
		src.WriteString("\n")
		for _, l := range filterDecl(t.decl) {
			src.WriteString(l)
			src.WriteString("\n")
		}
	}
	out, err := g.command(src.String(), "fmt")
	if err != nil {
		return nil, fmt.Errorf("%v\nsource:\n%s", err, src.String())
	}
	var decls [][]string
	for _, l := range strings.Split(out, "\n") {
		if strings.HasPrefix(l, "type ") {
			decls = append(decls, nil)
		}
		if len(decls) > 0 {
			decls[len(decls)-1] = append(decls[len(decls)-1], l)
		}
	}
	if len(decls) != len(types) {
		return nil, fmt.Errorf("pluto fmt returned %d type declarations for %d", len(decls), len(types))
	}
	lines := map[*docEntry]string{}
	for i, t := range types {
		lines[t] = collapse(strings.Join(decls[i], "\n")) + "  [" + t.kind + "]"
	}
	return lines, nil
}

// filterDecl edits a type declaration as pluto doc printed it. A struct
// keeps its exported fields, without tags or comments, and a final
// "_ unexported" field if it had others; the lines of the fields it drops
// and of their comments become blank, which ends an alignment section as
// the gap a dropped field leaves does. An interface loses the comments of
// its methods.
func filterDecl(decl []string) []string {
	first := decl[0]
	if len(decl) == 1 {
		// type Mark struct{ off uintptr }
		i := strings.Index(first, "struct{ ")
		if i < 0 || !strings.HasSuffix(first, " }") {
			return decl
		}
		var kept []string
		hidden := false
		for _, f := range strings.Split(first[i+len("struct{ "):len(first)-2], "; ") {
			if f, ok := filterField(f); ok {
				kept = append(kept, f)
			} else {
				hidden = true
			}
		}
		if hidden {
			kept = append(kept, "_ unexported")
		}
		return []string{first[:i] + "struct{ " + strings.Join(kept, "; ") + " }"}
	}
	isStruct := strings.HasSuffix(first, "struct {")
	if !isStruct && !strings.HasSuffix(first, "interface {") {
		return decl
	}
	out := []string{first}
	body := decl[1 : len(decl)-1]
	hidden := false
	insert := 1 // where "_ unexported" goes: after the last field kept
	for i := 0; i < len(body); {
		l := body[i]
		if l == "" || strings.HasPrefix(l, "\t//") {
			out = append(out, "")
			i++
			continue
		}
		// A field and the lines of its type that follow it.
		j := i + 1
		for j < len(body) && (strings.HasPrefix(body[j], "\t\t") || strings.HasPrefix(body[j], "\t}") || strings.HasPrefix(body[j], "\t)")) {
			j++
		}
		field := append([]string(nil), body[i:j]...)
		last := len(field) - 1
		field[last] = stripComment(field[last])
		keep := true
		if isStruct {
			var f string
			f, keep = filterField(strings.TrimPrefix(field[0], "\t"))
			field[0] = "\t" + f
		}
		if keep {
			out = append(out, field...)
			insert = len(out)
		} else {
			hidden = true
			for range field {
				out = append(out, "")
			}
		}
		i = j
	}
	if hidden {
		out = append(out[:insert], append([]string{"\t_ unexported"}, out[insert:]...)...)
	}
	return append(out, decl[len(decl)-1])
}

var namedField = regexp.MustCompile(`^([A-Za-z_][A-Za-z0-9_]*(?:, [A-Za-z_][A-Za-z0-9_]*)*)\s+(.*)$`)

// filterField takes one struct field without its indentation and returns
// it without a tag or comment and with only its exported names, and whether
// anything of it remains.
func filterField(f string) (string, bool) {
	f = stripTag(stripComment(f))
	if m := namedField.FindStringSubmatch(f); m != nil {
		var names []string
		for _, n := range strings.Split(m[1], ", ") {
			if exported(n) {
				names = append(names, n)
			}
		}
		return strings.Join(names, ", ") + " " + m[2], len(names) > 0
	}
	// An embedded field: *pkg.T[int] is named T.
	n := strings.TrimLeft(f, "*")
	if i := strings.IndexByte(n, '['); i >= 0 {
		n = n[:i]
	}
	if i := strings.LastIndexByte(n, '.'); i >= 0 {
		n = n[i+1:]
	}
	return f, exported(n)
}

// stripComment removes a trailing // comment from a line of source.
func stripComment(l string) string {
	var quote byte
	for i := 0; i < len(l); i++ {
		c := l[i]
		switch {
		case quote != 0:
			if c == '\\' && quote != '`' {
				i++
			} else if c == quote {
				quote = 0
			}
		case c == '"' || c == '\'' || c == '`':
			quote = c
		case c == '/' && i+1 < len(l) && l[i+1] == '/':
			return strings.TrimRight(l[:i], " \t")
		}
	}
	return l
}

// stripTag removes the tag from a field.
func stripTag(f string) string {
	if strings.HasSuffix(f, "`") || strings.HasSuffix(f, `"`) {
		q := f[len(f)-1]
		if i := strings.LastIndexByte(f[:len(f)-1], q); i > 0 && f[i-1] == ' ' {
			return strings.TrimRight(f[:i], " \t")
		}
	}
	return f
}
