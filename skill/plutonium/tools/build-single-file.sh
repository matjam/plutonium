#!/bin/sh
# Builds plutonium-guide.md: SKILL.md and every file of references/ in one
# Markdown file, for harnesses that have no skill support (opencode, Cursor,
# Aider, Continue, plain AGENTS.md or rules files).
#
# Usage: skill/plutonium/tools/build-single-file.sh [output]
#
# The output defaults to plutonium-guide.md next to SKILL.md. The frontmatter
# of SKILL.md is dropped; each reference becomes a section "Reference: ..."
# with its headings one level down; the checked fence markers (pluto-run,
# pluto-error E3301, ...) become plain go fences, with the expected error code
# as a first comment for the error examples. The result is about 7000 lines
# (roughly 90k tokens): for a smaller file, pass only what you need with
# the -only option, a comma-separated list of reference names without .md:
#
#   build-single-file.sh -only language-tour,ownership-and-memory,concurrency out.md
set -eu

only=""
if [ "${1:-}" = "-only" ]; then
	only=$2
	shift 2
fi

here=$(cd "$(dirname "$0")/.." && pwd)
out=${1:-$here/plutonium-guide.md}

# The order of the references; any file not listed follows, sorted.
order="language-tour library-cheatsheet ownership-and-memory concurrency errors-and-panics idioms idioms-types-memory idioms-memory idioms-concurrency go-to-plutonium kernel-mode known-gaps diagnostics stdlib stdlib-os-time-math stdlib-memory-concurrency stdlib-system"

names=""
for n in $order; do
	[ -f "$here/references/$n.md" ] && names="$names $n"
done
for f in "$here"/references/*.md; do
	n=$(basename "$f" .md)
	case " $order " in *" $n "*) ;; *) names="$names $n" ;; esac
done

wanted() {
	[ -z "$only" ] && return 0
	case ",$only," in *",$1,"*) return 0 ;; *) return 1 ;; esac
}

# normalize demotes headings by $1 levels outside fences and rewrites the
# fence markers of checked blocks.
normalize() {
	awk -v demote="$1" '
	BEGIN { fence = 0 }
	{
		line = $0
		if (line ~ /^```/) {
			if (!fence) {
				fence = 1
				info = substr(line, 4)
				if (info ~ /^pluto-error/) {
					split(info, a, " ")
					print "```go"
					print "// compile error " a[2] " expected"
					next
				}
				if (info ~ /^pluto-/) { print "```go"; next }
			} else {
				fence = 0
			}
			print line
			next
		}
		if (!fence && line ~ /^#+ /) {
			for (i = 0; i < demote; i++) line = "#" line
		}
		print line
	}'
}

{
	echo "# Plutonium guide"
	echo
	echo "Single-file form of the Plutonium skill (generated by skill/plutonium/tools/build-single-file.sh)."
	echo "Where the text says \`references/NAME.md\` or a file name such as \`ownership-and-memory.md\`, read the"
	echo "section \"Reference: NAME\" below. Examples marked \"compile error Exxxx expected\" must fail with that code;"
	echo "all others compile and run with the real compiler."
	echo
	# SKILL.md without its frontmatter.
	awk 'BEGIN { n = 0 } /^---$/ && n < 2 { n++; next } n >= 2 { print }' "$here/SKILL.md" | normalize 0
	for n in $names; do
		wanted "$n" || continue
		echo
		echo "<!-- references/$n.md -->"
		# The first line is the title: it becomes the section heading.
		head -n 1 "$here/references/$n.md" | sed 's/^# /## Reference: /'
		tail -n +2 "$here/references/$n.md" | normalize 1
	done
} > "$out"

echo "wrote $out ($(wc -l < "$out") lines)" >&2
