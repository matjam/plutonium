// Command gendiag writes the error code reference of the Plutonium skill
// (references/diagnostics.md) from the compiler's diagnostics catalog
// (internal/diag), the same text `pluto explain` prints.
//
// Run it from the repository root after the catalog changes:
//
//	go run ./skill/plutonium/tools/gendiag
//
// The -out flag names the file to write.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/matjam/plutonium/internal/diag"
)

// A section is a range of codes with its heading.
type section struct {
	from, to int
	title    string
	note     string
}

var sections = []section{
	{1, 999, "E0001 to E0999: Go's type rules",
		"These are the type checker's errors as Go has them (numbered as go/types numbers them), with the same meaning."},
	{1000, 1999, "E1000 to E1999: syntax errors",
		"The parser. The message names the token it did not expect."},
	{2000, 2499, "E2000 to E2499: Plutonium rules checked by the type checker",
		"Removed constructs, enums, unions, packed types, defaults, the or clause, `errors.New`, sendability, indexing containers."},
	{2500, 2999, "E2500 to E2999: Plutonium rules checked while compiling",
		"Directives, C and assembly linkage, per-CPU variables, kernel rules, `defer`, `task`, schedulers, interrupt context."},
	{3000, 3999, "E3000 to E3999: ownership, lifetimes and races",
		"Views of frames (E30xx), closures (E31xx), owner types (E32xx), moves and drops (E33xx), scoped tasks (E34xx), data races (E35xx)."},
	{4000, 4999, "E4000 to E4999: packages and modules", "Finding, loading and naming packages; `pluto.mod`."},
	{5000, 5999, "E5000 to E5999: assembling and linking", "The assembler, linker and object files."},
	{9000, 9999, "E9000 to E9999: compiler errors", "A bug in the compiler. Report it with the program."},
}

func main() {
	out := flag.String("out", "skill/plutonium/references/diagnostics.md", "file to write")
	flag.Parse()
	var b bytes.Buffer
	fmt.Fprint(&b, `# Diagnostics

<!-- Generated by skill/plutonium/tools/gendiag from internal/diag. Do not edit; regenerate. -->

Every compile error ends with a code. `+"`pluto explain E3301`"+` prints the long explanation with an example; `+"`pluto explain`"+`
alone lists every code. Each row below gives the code, its name, what is wrong in one sentence and the usual fix.
Messages name the variables and lines involved; read them before this table. `+"`--brief`"+` (or `+"`PLUTO_BRIEF=1`"+`)
prints only the one-line message. Pick the first error in the output: later ones are often consequences.

How to read a diagnostic: `+"`file:line:col: message`"+`, then an indented explanation, a suggested fix, the specification
section (`+"`section 18.3`"+`: read `+"`docs/spec/language/18-ownership-and-memory.md`"+`) and the `+"`pluto explain`"+` line.

`)
	codes := diag.Codes()
	for _, s := range sections {
		var rows []*diag.Entry
		for _, c := range codes {
			var n int
			if _, err := fmt.Sscanf(string(c), "E%d", &n); err != nil {
				continue
			}
			if n >= s.from && n <= s.to {
				rows = append(rows, diag.Lookup(c))
			}
		}
		if len(rows) == 0 {
			continue
		}
		fmt.Fprintf(&b, "## %s\n\n%s\n\n| Code | Name | Meaning | Usual fix |\n|---|---|---|---|\n", s.title, s.note)
		for _, e := range rows {
			f := fix(e)
			if f == "" {
				f = "`pluto explain " + string(e.Code) + "`"
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", e.Code, e.Name, cell(meaning(e)), cell(f))
		}
		fmt.Fprintln(&b)
	}
	if err := os.WriteFile(*out, b.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gendiag:", err)
		os.Exit(1)
	}
}

// meaning is the first sentence of the entry's explanation.
func meaning(e *diag.Entry) string {
	paras := paragraphs(e.Text)
	if len(paras) == 0 {
		return e.Name
	}
	return firstSentence(paras[0])
}

// fix is the entry's fix: its introduction, or else the first sentence of
// the last paragraph of the explanation when that tells what to do.
func fix(e *diag.Entry) string {
	if e.Fix != nil && e.Fix.Intro != "" {
		s := e.Fix.Intro
		if code := firstLine(e.Fix.Code); code != "" && len(code) <= 60 {
			s += ": `" + code + "`"
		}
		return s
	}
	paras := paragraphs(e.Text)
	for i := len(paras) - 1; i >= 1; i-- {
		first, _, _ := strings.Cut(paras[i], " ")
		if imperative[first] {
			return firstSentence(paras[i])
		}
	}
	return ""
}

// imperative lists the verbs with which the catalog's advice paragraphs
// begin.
var imperative = map[string]bool{
	"Use": true, "Write": true, "Declare": true, "Move": true, "Pass": true, "Add": true, "Make": true,
	"Wrap": true, "Replace": true, "Return": true, "Call": true, "Give": true, "Put": true, "Take": true,
	"Send": true, "Start": true, "Keep": true, "Check": true, "Hold": true, "Allocate": true, "Copy": true,
	"Change": true, "Remove": true, "Split": true, "Store": true, "Convert": true, "Lock": true, "Join": true,
	"Wait": true, "Order": true, "Reorder": true, "Assign": true, "Read": true, "Import": true, "Build": true,
	"Mark": true, "Rename": true, "Name": true, "Set": true, "Open": true, "Close": true, "Try": true,
	"Avoid": true, "Let": true, "Delete": true, "Define": true, "Create": true, "Fix": true, "Report": true,
	"Test": true, "Update": true, "Install": true, "Choose": true, "Remember": true, "Break": true,
}

func paragraphs(text string) []string {
	var out []string
	for _, p := range strings.Split(text, "\n") {
		if p = strings.TrimSpace(p); p != "" {
			out = append(out, p)
		}
	}
	return out
}

// firstLine returns the first line of code that is not an import or
// package clause.
func firstLine(s string) string {
	for _, line := range strings.Split(s, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "import") || strings.HasPrefix(line, "package") || strings.HasPrefix(line, "//") {
			continue
		}
		return line
	}
	return ""
}

// sentences returns the sentences of p, split at full stops that end a
// sentence.
func sentences(p string) []string {
	p = strings.Join(strings.Fields(p), " ")
	var out []string
	start := 0
	for i := 0; i+1 < len(p); i++ {
		if p[i] == '.' && p[i+1] == ' ' && i > start+3 {
			out = append(out, p[start:i+1])
			start = i + 2
		}
	}
	if start < len(p) {
		out = append(out, p[start:])
	}
	return out
}

// firstSentence returns the first sentence of p, or the first two when the
// first is short, shortened to a readable length.
func firstSentence(p string) string {
	ss := sentences(p)
	if len(ss) == 0 {
		return ""
	}
	out := ss[0]
	for _, s := range ss[1:] {
		if len(out) >= 100 || len(out)+1+len(s) > 230 {
			break
		}
		out += " " + s
	}
	if len(out) > 230 {
		out = out[:227]
		if i := strings.LastIndex(out, " "); i > 100 {
			out = out[:i]
		}
		out += "..."
	}
	return out
}

// cell makes text safe for a table cell.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	return strings.ReplaceAll(s, "\n", " ")
}
