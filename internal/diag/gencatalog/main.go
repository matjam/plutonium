// Command gencatalog writes internal/diag/catalog_go.go from the
// documentation of the type checker's error codes in
// internal/types2/errors/codes.go, which comes from go/types. Each code's
// comment gives a description, sometimes a quote from the Go spec, and
// examples; the catalog uses them as the explanation of codes that have no
// hand-written one.
//
// Run it with go generate in internal/diag.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"strings"
)

func main() {
	in := flag.String("in", "../types2/errors/codes.go", "the error codes file")
	out := flag.String("out", "catalog_go.go", "the file to write")
	flag.Parse()

	docs, err := parseCodes(*in)
	if err != nil {
		log.Fatal(err)
	}
	src, err := generate(docs)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// A codeDoc is the documentation of one error code.
type codeDoc struct {
	value    int
	name     string
	text     string   // the description, one paragraph per line
	spec     string   // a quote from the Go spec, or ""
	examples []string // example programs
}

// parseCodes reads the constants of type Code and their comments. The
// file has a block holding InvalidSyntaxTree = -1 and a block counting from
// iota = 0, in which a blank name reserves a value.
func parseCodes(file string) ([]codeDoc, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, file, nil, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	var docs []codeDoc
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		iota := 0
		explicit := false
		for _, spec := range gd.Specs {
			vs := spec.(*ast.ValueSpec)
			value := iota
			if len(vs.Values) == 1 {
				if lit, ok := vs.Values[0].(*ast.UnaryExpr); ok && lit.Op == token.SUB {
					value, explicit = -1, true
				}
			}
			iota++
			name := vs.Names[0].Name
			if name == "_" || explicit || name == "Test" {
				continue
			}
			doc := parseDoc(name, vs.Doc)
			doc.value = value
			docs = append(docs, doc)
		}
	}
	return docs, nil
}

// parseDoc splits a code's comment into description, spec quote and
// examples. Lines indented by a space after the comment marker are code
// or quotes; a TODO paragraph is left out.
func parseDoc(name string, cg *ast.CommentGroup) codeDoc {
	doc := codeDoc{name: name}
	if cg == nil {
		return doc
	}
	var paras [][]string
	var cur []string
	flush := func() {
		if len(cur) > 0 {
			paras = append(paras, cur)
			cur = nil
		}
	}
	for _, c := range cg.List {
		line := strings.TrimPrefix(c.Text, "//")
		if strings.TrimSpace(line) == "" {
			flush()
			continue
		}
		cur = append(cur, line)
	}
	flush()

	var text []string
	for i := 0; i < len(paras); i++ {
		p := paras[i]
		first := strings.TrimSpace(p[0])
		switch {
		case strings.HasPrefix(first, "TODO"):
		case first == "Example:":
			doc.examples = append(doc.examples, code(p[1:]))
		case first == "Per the spec:":
			var q []string
			for _, l := range p[1:] {
				q = append(q, strings.TrimSpace(l))
			}
			doc.spec = strings.Join(q, " ")
		case strings.HasPrefix(p[0], " ") && len(doc.examples) > 0:
			// A blank line inside an example.
			doc.examples[len(doc.examples)-1] += "\n\n" + code(p)
		default:
			var words []string
			for _, l := range p {
				words = append(words, strings.TrimSpace(l))
			}
			text = append(text, strings.Join(words, " "))
		}
	}
	doc.text = strings.Join(text, "\n")
	return doc
}

// code turns example lines, indented by one space after the comment
// marker, into source text.
func code(lines []string) string {
	var out []string
	for _, l := range lines {
		l = strings.TrimPrefix(l, " ")
		l = strings.TrimPrefix(l, " ") // some examples indent by two
		out = append(out, l)
	}
	return strings.Join(out, "\n")
}

func generate(docs []codeDoc) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by gencatalog from internal/types2/errors/codes.go; DO NOT EDIT.\n\n")
	b.WriteString("package diag\n\n")
	b.WriteString("// goDocs documents the type checker's error codes that come from go/types,\n")
	b.WriteString("// in the words of go/types.\n")
	b.WriteString("var goDocs = []goDoc{\n")
	for _, d := range docs {
		fmt.Fprintf(&b, "\t{Value: %d, Name: %q,\n", d.value, d.name)
		fmt.Fprintf(&b, "\t\tText: %q,\n", d.text)
		if d.spec != "" {
			fmt.Fprintf(&b, "\t\tSpec: %q,\n", d.spec)
		}
		if len(d.examples) > 0 {
			b.WriteString("\t\tExamples: []string{\n")
			for _, e := range d.examples {
				fmt.Fprintf(&b, "\t\t\t%q,\n", e)
			}
			b.WriteString("\t\t},\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
