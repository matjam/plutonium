// Command mkunicode generates lib/pluto/unicode/tables.p, the Unicode tables
// of the pluto/unicode package, from the tables of the Go toolchain that
// runs it. Go generates its own unicode/tables.go from the Unicode Character
// Database with golang.org/x/text/internal/export/unicode; taking the
// toolchain's file as the source makes the Plutonium tables identical to
// Go's for the same Go release (Go 1.27.1 carries Unicode 17.0.0) and keeps
// "go generate" offline and reproducible.
//
// The output is Go's tables.go without the map variables (Categories,
// CategoryAliases, Scripts, Properties, FoldCategory and FoldScript):
// Plutonium has no built-in map, and the tables they name are all
// available as package variables (unicode.Han, unicode.Lu, ...). Every other
// declaration is copied unchanged, comments included.
//
//go:generate go run . -o ../../lib/pluto/unicode/tables.p
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

const header = `// Copyright 2009 The Go Authors. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the LICENSE file.

// Code generated by tools/mkunicode from Go's unicode/tables.go (Go %s,
// Unicode %s). DO NOT EDIT.

package unicode

`

func main() {
	log.SetPrefix("mkunicode: ")
	log.SetFlags(0)
	out := flag.String("o", "", "output file (default: standard output)")
	flag.Parse()

	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		log.Fatal(err)
	}
	goVersion, err := exec.Command("go", "env", "GOVERSION").Output()
	if err != nil {
		log.Fatal(err)
	}
	path := filepath.Join(strings.TrimSpace(string(goroot)), "src", "unicode", "tables.go")
	src, err := os.ReadFile(path)
	if err != nil {
		log.Fatal(err)
	}
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, src, parser.ParseComments)
	if err != nil {
		log.Fatal(err)
	}

	version := ""
	var body bytes.Buffer
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok {
			log.Fatalf("%s: unexpected declaration at %s", path, fset.Position(decl.Pos()))
		}
		if isMapVar(gd) {
			continue
		}
		if gd.Tok == token.CONST && len(gd.Specs) == 1 {
			if vs := gd.Specs[0].(*ast.ValueSpec); vs.Names[0].Name == "Version" {
				version = strings.Trim(vs.Values[0].(*ast.BasicLit).Value, `"`)
			}
		}
		start := gd.Pos()
		if gd.Doc != nil {
			start = gd.Doc.Pos()
		}
		if text, ok := arrayForm(fset, src, gd); ok {
			body.WriteString(text)
		} else {
			body.Write(src[fset.Position(start).Offset:fset.Position(gd.End()).Offset])
		}
		body.WriteString("\n\n")
	}
	if version == "" {
		log.Fatalf("%s: no Version constant", path)
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, header, strings.TrimPrefix(strings.TrimSpace(string(goVersion)), "go"), version)
	buf.Write(body.Bytes())
	res, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("formatting the tables: %v", err)
	}
	if *out == "" {
		if _, err := os.Stdout.Write(res); err != nil {
			log.Fatal(err)
		}
		return
	}
	if err := os.WriteFile(*out, res, 0o644); err != nil {
		log.Fatal(err)
	}
}

// arrayForm rewrites a declaration of a table whose ranges are a slice
// literal, so that the elements are an array and the slice a view of it:
//
//	var _Lu = &RangeTable{R16: []Range16{...}, LatinOffset: 3}
//
// becomes
//
//	var _Lu_R16 = [...]Range16{...}
//	var _Lu = &RangeTable{R16: _Lu_R16[:], LatinOffset: 3}
//
// and var caseOrbit = []foldPair{...} becomes an array caseOrbit_ and
// var caseOrbit = caseOrbit_[:]. The Plutonium compiler writes an array of
// constants into the program's data and the pointer to it into the table
// statically, where a slice literal in a package-level initializer is built
// by code that runs when the program starts, about 14 bytes of code per
// range. It reports whether gd had that form.
func arrayForm(fset *token.FileSet, src []byte, gd *ast.GenDecl) (string, bool) {
	if gd.Tok != token.VAR || len(gd.Specs) != 1 {
		return "", false
	}
	vs := gd.Specs[0].(*ast.ValueSpec)
	if len(vs.Names) != 1 || len(vs.Values) != 1 {
		return "", false
	}
	name := vs.Names[0].Name
	text := func(from, to token.Pos) string {
		return string(src[fset.Position(from).Offset:fset.Position(to).Offset])
	}
	doc := ""
	if gd.Doc != nil {
		doc = text(gd.Doc.Pos(), gd.Doc.End()) + "\n"
	}
	var out strings.Builder

	// elements returns the array declaration for the slice literal lit and
	// the name of the array.
	elements := func(arrName string, lit *ast.CompositeLit) (string, bool) {
		at, ok := lit.Type.(*ast.ArrayType)
		if !ok || at.Len != nil {
			return "", false
		}
		fmt.Fprintf(&out, "var %s = [...]%s{%s}\n\n", arrName, text(at.Elt.Pos(), at.Elt.End()), text(lit.Lbrace+1, lit.Rbrace))
		return arrName, true
	}

	switch v := vs.Values[0].(type) {
	case *ast.CompositeLit:
		// var NAME = []T{...}
		arr, ok := elements(name+"_", v)
		if !ok {
			return "", false
		}
		out.WriteString(doc)
		fmt.Fprintf(&out, "var %s = %s[:]", name, arr)
		return out.String(), true
	case *ast.UnaryExpr:
		// var NAME = &RangeTable{...}
		cl, ok := v.X.(*ast.CompositeLit)
		if !ok || v.Op != token.AND {
			return "", false
		}
		if id, ok := cl.Type.(*ast.Ident); !ok || id.Name != "RangeTable" {
			return "", false
		}
		var fields []string
		for _, elt := range cl.Elts {
			kv := elt.(*ast.KeyValueExpr)
			key := kv.Key.(*ast.Ident).Name
			switch key {
			case "R16", "R32":
				arr, ok := elements(name+"_"+key, kv.Value.(*ast.CompositeLit))
				if !ok {
					return "", false
				}
				fields = append(fields, fmt.Sprintf("%s: %s[:],", key, arr))
			default:
				fields = append(fields, fmt.Sprintf("%s: %s,", key, text(kv.Value.Pos(), kv.Value.End())))
			}
		}
		out.WriteString(doc)
		fmt.Fprintf(&out, "var %s = &RangeTable{\n%s\n}", name, strings.Join(fields, "\n"))
		return out.String(), true
	}
	return "", false
}

// isMapVar reports whether gd declares a variable whose value is a map
// literal.
func isMapVar(gd *ast.GenDecl) bool {
	if gd.Tok != token.VAR {
		return false
	}
	for _, spec := range gd.Specs {
		vs := spec.(*ast.ValueSpec)
		for _, v := range vs.Values {
			if cl, ok := v.(*ast.CompositeLit); ok {
				if _, ok := cl.Type.(*ast.MapType); ok {
					return true
				}
			}
		}
	}
	return false
}
