package main

import (
	"fmt"
	"math/rand"
	"slices"
	"strconv"
	"strings"
)

// Options control what the generator may produce.
type Options struct {
	// RangeWrites lets a loop that ranges over an array with a value
	// variable write to that array. Go ranges over a copy of the array;
	// Plutonium ranged in place until main's ee9b93a.
	RangeWrites bool
}

const (
	fnBudget   = 20000  // estimated dynamic statements per function call
	mainBudget = 400000 // and for main
	maxDepth   = 3      // nesting of compound statements
	maxLines   = 70     // lines per function before it stops adding statements
)

// A variable is a name in scope.
type variable struct {
	name     string
	t        *typ
	readonly bool
	global   bool
	level    int // closure nesting level of the function declaring it
	used     bool

	// For integer loop variables: the values the variable takes in the
	// body, and a slice it indexes safely (0 <= v < len(boundSlice)).
	hasRange   bool
	lo, hi     int64
	boundSlice *variable

	sliceLen int  // slices: a lower bound on the length, at least 1
	owned    bool // slices and pointers: the memory belongs to the declaring function
	sliced   bool // a slice of or pointer into this variable's memory exists

	closure *closureInfo
}

type closureInfo struct {
	params []*typ
	result *typ
	pure   bool
	cost   int64
}

type fnInfo struct {
	name    string
	recv    *variable // the receiver of a method
	tparam  *typ      // the type parameter of a generic function
	params  []*variable
	results []*typ
	pure    bool
	cost    int64
	text    string
}

type scope struct {
	parent *scope
	vars   []*variable
}

type loopInfo struct {
	label     string
	labelUsed bool
}

// A ctx is the function (or function literal) being generated.
type ctx struct {
	level         int
	results       []*typ
	writeGlobal   bool // may write globals and memory it does not own
	minWriteLevel int  // variables of enclosing functions below this level are read-only
	isMain        bool // main, which does not return early so that all output appears
	tparam        *typ // the type parameter of a generic function
	named         bool // the results are named, so a bare return is allowed
	mult          int64
	cost          int64
	budget        int64
	loops         []*loopInfo
	hash          *variable
	depth         int
}

type gen struct {
	r       *rand.Rand
	opt     Options
	types   map[string]*typ
	structs []*typ
	globals []*variable
	funcs   []*fnInfo
	nfuncs  int // functions callable from the current one
	lines   []string
	indent  int
	sc      *scope
	cx      *ctx
	seq     int
	ranged  map[*variable]bool

	globalText strings.Builder
	strs       []str // package-level strings

	// The interface Ifc { Get(int) int }, the named integer type N, and
	// the types that implement Ifc, if the program has them.
	ifc          *typ
	named        *typ
	implementers []*typ
	inGet        bool

	loopStart  int // index of the line where the loop being generated starts
	callDepth  int // calls being generated inside other calls' arguments
	indexDepth int // index expressions being generated inside index expressions
}

// Generate returns a program in the common subset of Go and Plutonium.
// The same seed and options always give the same program.
func Generate(seed int64, opt Options) string {
	g := &gen{
		r:      rand.New(rand.NewSource(seed)),
		opt:    opt,
		types:  map[string]*typ{},
		ranged: map[*variable]bool{},
	}
	for _, t := range intTypes {
		g.types[t.String()] = t
	}
	g.types["bool"] = tBool
	g.types["float64"] = tFloat64
	g.types["float32"] = tFloat32
	return g.program(seed)
}

func (g *gen) program(seed int64) string {
	var out strings.Builder
	fmt.Fprintf(&out, "package main\n\n// Generated by tools/difftest, seed %d.\n\n", seed)

	for i, n := 0, 1+g.r.Intn(3); i < n; i++ {
		t := g.newStruct()
		out.WriteString("type " + t.name + " struct {\n")
		for _, f := range t.fields {
			fmt.Fprintf(&out, "\t%s %s\n", f.name, f.t)
		}
		out.WriteString("}\n\n")
	}

	g.sc = &scope{}
	// At least one global of every integer type, so that a non-constant
	// expression of any type is always available. More globals are added
	// as functions need them, and all are written before the functions.
	for _, t := range intTypes {
		g.newGlobal(t)
	}
	for i, n := 0, 2+g.r.Intn(4); i < n; i++ {
		g.newGlobal(g.randType(false))
	}

	var funcs strings.Builder
	funcs.WriteString(f2iFunc)
	if g.chance(3) {
		out.WriteString("type Ifc interface {\n\tGet(x int) int\n}\n\ntype N int32\n\n")
		g.ifc = &typ{kind: kIface, name: "Ifc"}
		g.named = &typ{kind: kInt, name: "N", bits: 32, signed: true}
		g.implementers = append([]*typ{g.named}, g.structs...)
		// Get methods do not call Get, which could recurse forever.
		g.inGet = true
		for _, t := range g.implementers {
			funcs.WriteString(g.getMethod(t))
		}
		g.inGet = false
	}
	for i, n := 0, 3+g.r.Intn(4); i < n; i++ {
		g.nfuncs = i
		f := g.function(i)
		g.funcs = append(g.funcs, f)
		funcs.WriteString(f.text)
	}
	g.nfuncs = len(g.funcs)
	funcs.WriteString(g.mainFunc())

	out.WriteString(g.globalText.String())
	out.WriteString("\n")
	out.WriteString(funcs.String())
	return out.String()
}

func (g *gen) name(prefix string) string {
	g.seq++
	return prefix + strconv.Itoa(g.seq)
}

func (g *gen) chance(n int) bool { return g.r.Intn(n) == 0 }

// ----------------------------------------------------------------------------
// Types

func (g *gen) canon(t *typ) *typ {
	k := t.String()
	if c, ok := g.types[k]; ok {
		return c
	}
	g.types[k] = t
	return t
}

func (g *gen) arrayOf(elem *typ, n int) *typ { return g.canon(&typ{kind: kArray, elem: elem, n: n}) }
func (g *gen) sliceOf(elem *typ) *typ        { return g.canon(&typ{kind: kSlice, elem: elem}) }

// randInt picks an integer type, which in a generic function may be its
// type parameter.
func (g *gen) randInt() *typ {
	if g.cx != nil && g.cx.tparam != nil && g.chance(3) {
		return g.cx.tparam
	}
	return g.concreteInt()
}

func (g *gen) concreteInt() *typ {
	if g.chance(4) {
		return tInt
	}
	return intTypes[g.r.Intn(len(intTypes))]
}

func (g *gen) randLen() int {
	return []int{1, 2, 3, 4, 4, 5, 7, 8, 8, 16}[g.r.Intn(10)]
}

// randElem picks an element type for an array, slice or pointer: never a
// type parameter, which keeps instantiation to plain substitution.
func (g *gen) randElem() *typ {
	if len(g.structs) > 0 && g.chance(5) {
		return g.structs[g.r.Intn(len(g.structs))]
	}
	if g.chance(10) {
		return g.randFloat()
	}
	return g.concreteInt()
}

// randType picks a value type: an integer, bool, array or struct, or with
// refs set also a slice or pointer.
func (g *gen) randType(refs bool) *typ {
	switch n := g.r.Intn(100); {
	case n < 47:
		return g.randInt()
	case n < 52:
		return g.randFloat()
	case n < 60:
		return tBool
	case n < 72:
		return g.arrayOf(g.randElem(), g.randLen())
	case n < 85 || !refs:
		if len(g.structs) == 0 {
			return g.randInt()
		}
		return g.structs[g.r.Intn(len(g.structs))]
	case n < 93:
		return g.sliceOf(g.randElem())
	default:
		var elem *typ
		switch g.r.Intn(3) {
		case 0:
			elem = g.concreteInt()
		case 1:
			elem = g.arrayOf(g.randElem(), g.randLen())
		default:
			elem = g.randElem()
		}
		return g.canon(&typ{kind: kPtr, elem: elem})
	}
}

func (g *gen) newStruct() *typ {
	t := &typ{kind: kStruct, name: fmt.Sprintf("S%d", len(g.structs))}
	for i, n := 0, 2+g.r.Intn(6); i < n; i++ {
		var ft *typ
		switch k := g.r.Intn(20); {
		case k < 13:
			ft = g.concreteInt()
		case k < 14:
			ft = g.randFloat()
		case k < 16:
			ft = tBool
		case k < 19:
			ft = g.arrayOf(g.concreteInt(), 2+g.r.Intn(4))
		default:
			if len(g.structs) > 0 {
				ft = g.structs[g.r.Intn(len(g.structs))]
			} else {
				ft = g.concreteInt()
			}
		}
		t.fields = append(t.fields, field{name: fmt.Sprintf("f%d", i), t: ft})
	}
	g.types[t.name] = t
	g.structs = append(g.structs, t)
	return t
}

// reach reports whether a value of type want is reachable from t by
// selecting fields and indexing.
func reach(t, want *typ) bool {
	if t == want {
		return true
	}
	switch t.kind {
	case kStruct:
		for _, f := range t.fields {
			if reach(f.t, want) {
				return true
			}
		}
	case kArray, kSlice, kPtr:
		return reach(t.elem, want)
	}
	return false
}

// ----------------------------------------------------------------------------
// Constants

func (g *gen) constant(t *typ) string {
	if t.kind == kBool {
		if g.chance(2) {
			return "true"
		}
		return "false"
	}
	if t.kind == kFloat {
		return g.floatConst(t, false)
	}
	if t.signed {
		return strconv.FormatInt(g.signedConst(t), 10)
	}
	return strconv.FormatUint(g.unsignedConst(t), 10)
}

func (g *gen) signedConst(t *typ) int64 {
	switch g.r.Intn(12) {
	case 0:
		return 0
	case 1:
		return 1
	case 2:
		return -1
	case 3:
		return t.minS() + int64(g.r.Intn(2))
	case 4:
		return t.maxS() - int64(g.r.Intn(2))
	case 5:
		v := int64(1) << g.r.Intn(t.bits-1)
		v += int64(g.r.Intn(3) - 1)
		if g.chance(2) {
			v = -v
		}
		return v
	case 6, 7, 8:
		return int64(g.r.Intn(41) - 20)
	default:
		sh := 64 - t.bits
		return int64(g.r.Uint64()<<sh) >> sh
	}
}

func (g *gen) unsignedConst(t *typ) uint64 {
	switch g.r.Intn(11) {
	case 0:
		return 0
	case 1:
		return 1
	case 2:
		return t.maxU()
	case 3:
		return t.maxU() - 1
	case 4:
		return t.maxU() >> 1
	case 5:
		v := uint64(1) << g.r.Intn(t.bits)
		if v > 1 {
			v += uint64(g.r.Intn(3)) - 1
		}
		return v
	case 6, 7, 8:
		return uint64(g.r.Intn(30))
	default:
		return g.r.Uint64() & t.maxU()
	}
}

// divisor returns a constant divisor for t: never 0 or -1.
func (g *gen) divisor(t *typ) string {
	var cands []int64
	cands = append(cands, 1, 2, 3, 5, 7, 10, 16, 641, 1000)
	if t.bits >= 32 {
		cands = append(cands, 1000000007, 1<<20, 65535, 274177)
	}
	if t.signed {
		cands = append(cands, -2, -3, -7, -8, -10, -16, t.maxS(), t.minS(), t.minS()+1)
	}
	if !t.signed {
		if g.chance(6) {
			u := t.maxU() - uint64(g.r.Intn(3))
			if g.chance(2) {
				u = t.maxU()>>1 + 1 + uint64(g.r.Intn(2))
			}
			return strconv.FormatUint(u, 10)
		}
	}
	for {
		v := cands[g.r.Intn(len(cands))]
		if t.signed && (v < t.minS() || v > t.maxS()) {
			continue
		}
		if !t.signed && uint64(v) > t.maxU() {
			continue
		}
		return strconv.FormatInt(v, 10)
	}
}

// ----------------------------------------------------------------------------
// Scopes and variables

func (g *gen) push() { g.sc = &scope{parent: g.sc} }

// pop closes the innermost scope, first using every variable declared in
// it that nothing read, as Go requires.
func (g *gen) pop() {
	for _, v := range g.sc.vars {
		if v.used {
			continue
		}
		h := g.cx.hash
		switch {
		case v.closure != nil:
			g.line("_ = %s", v.name)
		case v.t.kind == kInt && h != nil && g.canWriteRoot(h):
			g.line("%s = %s*31 + uint64(%s)", h.name, h.name, v.name)
			h.used = true
		case v.t.kind == kBool && h != nil && g.canWriteRoot(h):
			g.line("if %s {", v.name)
			g.line("\t%s++", h.name)
			g.line("}")
			h.used = true
		case v.t.kind == kFloat && h != nil && g.canWriteRoot(h):
			g.line("%s = %s*31 + uint64(%s)", h.name, h.name, toInt(v.name, v.t))
			h.used = true
		default:
			g.line("_ = %s", v.name)
		}
		v.used = true
	}
	g.sc = g.sc.parent
}

func (g *gen) declare(v *variable) *variable {
	v.level = g.cx.level
	g.sc.vars = append(g.sc.vars, v)
	return v
}

// visible returns the variables in scope, innermost first, leaving out
// those hidden by an inner variable of the same name.
func (g *gen) visible() []*variable {
	var out []*variable
	seen := map[string]bool{}
	for s := g.sc; s != nil; s = s.parent {
		for _, v := range s.vars {
			if !seen[v.name] {
				out = append(out, v)
			}
		}
		for _, v := range s.vars {
			seen[v.name] = true
		}
	}
	return out
}

// shadowName returns the name of a variable declared in an enclosing
// block, for a new variable to hide, or a fresh name.
func (g *gen) shadowName() string {
	if g.sc != nil && g.sc.parent != nil && g.chance(6) {
		var cands []string
		for s := g.sc.parent; s != nil; s = s.parent {
			for _, v := range s.vars {
				if v.closure == nil && v != g.cx.hash {
					cands = append(cands, v.name)
				}
			}
		}
		here := map[string]bool{}
		for _, v := range g.sc.vars {
			here[v.name] = true
		}
		if len(cands) > 0 {
			if n := cands[g.r.Intn(len(cands))]; !here[n] {
				return n
			}
		}
	}
	return g.name("v")
}

func (g *gen) canWriteRoot(v *variable) bool {
	if v.readonly || g.ranged[v] || v.closure != nil {
		return false
	}
	if v.global {
		return g.cx.writeGlobal
	}
	return v.level >= g.cx.minWriteLevel
}

// canWriteElems reports whether the elements of slice v may be written.
func (g *gen) canWriteElems(v *variable) bool {
	return g.canWriteRoot(v) && (v.owned || g.cx.writeGlobal)
}

