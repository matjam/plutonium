// Output

func (g *gen) line(format string, args ...any) {
	g.lines = append(g.lines, strings.Repeat("\t", g.indent)+fmt.Sprintf(format, args...))
}

func (g *gen) addCost(n int64) { g.cx.cost += g.cx.mult * n }

func (g *gen) overBudget() bool { return g.cx.cost > g.cx.budget }

// ----------------------------------------------------------------------------
// Places: variables, fields and elements

// place returns a path to a value of type want, rooted at a visible
// variable, or "" if there is none. For writes, only writable roots are
// considered, and a slice root must be indexed.
func (g *gen) place(want *typ, write bool) string {
	p, _ := g.placeRoot(want, write)
	return p
}

// placeRoot is place that also returns the root variable.
func (g *gen) placeRoot(want *typ, write bool) (string, *variable) {
	var cands []*variable
	for _, v := range g.visible() {
		if v.closure != nil || !reach(v.t, want) {
			continue
		}
		if write {
			if v.t.ref() {
				if !g.canWriteElems(v) {
					continue
				}
			} else if !g.canWriteRoot(v) {
				continue
			}
		}
		cands = append(cands, v)
	}
	// Mostly locals, most often recently declared ones.
	if len(cands) == 0 || g.chance(5) {
		for _, v := range g.globals {
			if !reach(v.t, want) || (write && !g.canWriteRoot(v)) {
				continue
			}
			cands = append(cands, v)
		}
	}
	if len(cands) == 0 {
		return "", nil
	}
	v := cands[g.r.Intn(len(cands))]
	if !g.chance(3) {
		v = cands[g.r.Intn(len(cands)/2+1)]
	}
	if !write {
		v.used = true
	}
	return g.descend(v.name, v.t, want, v), v
}

func (g *gen) descend(base string, t, want *typ, root *variable) string {
	if t == want {
		return base
	}
	switch t.kind {
	case kStruct:
		var fs []field
		for _, f := range t.fields {
			if reach(f.t, want) {
				fs = append(fs, f)
			}
		}
		f := fs[g.r.Intn(len(fs))]
		return g.descend(base+"."+f.name, f.t, want, nil)
	case kArray:
		return g.descend(base+"["+g.index(t.n, nil)+"]", t.elem, want, nil)
	case kSlice:
		return g.descend(base+"["+g.index(root.sliceLen, root)+"]", t.elem, want, nil)
	case kPtr:
		if t.elem == want {
			return "(*" + base + ")"
		}
		// Selectors and indexing dereference the pointer.
		return g.descend(base, t.elem, want, nil)
	}
	panic("descend: unreachable type " + t.String())
}

// index returns an expression in [0, n). For a slice, n is a lower bound
// on its length and sl the slice.
func (g *gen) index(n int, sl *variable) string {
	var loopVars []string
	var shifted []string
	for _, v := range g.visible() {
		if v.t == nil || v.t.kind != kInt || v.t.param {
			continue
		}
		if sl != nil && v.boundSlice == sl {
			loopVars = append(loopVars, v.name)
		}
		if !v.hasRange {
			continue
		}
		if v.lo >= 0 && v.hi < int64(n) {
			loopVars = append(loopVars, v.name)
		} else if v.lo > 0 && v.hi-v.lo < int64(n) {
			shifted = append(shifted, fmt.Sprintf("(%s - %d)", v.name, v.lo))
		}
	}
	// Index expressions inside index expressions stay simple.
	g.indexDepth++
	defer func() { g.indexDepth-- }()
	choices := 9
	if g.indexDepth > 1 {
		choices = 5
	}
	for {
		switch g.r.Intn(choices) {
		case 0, 1:
			return strconv.Itoa(g.r.Intn(n))
		case 2, 3:
			if len(loopVars) > 0 {
				v := loopVars[g.r.Intn(len(loopVars))]
				for _, x := range g.visible() {
					if x.name == v {
						x.used = true
					}
				}
				return v
			}
		case 4:
			if len(shifted) > 0 {
				return shifted[g.r.Intn(len(shifted))]
			}
		case 5:
			if n&(n-1) == 0 {
				// Not a type parameter, which cannot be an index.
				return fmt.Sprintf("(%s & %d)", g.intExpr(g.concreteInt(), 1, true).s, n-1)
			}
		case 6:
			e := g.intExpr(g.randInt(), 1, true).s
			if sl != nil && g.chance(2) {
				sl.used = true
				return fmt.Sprintf("(uint(%s) %% uint(len(%s)))", e, sl.name)
			}
			return fmt.Sprintf("(uint(%s) %% %d)", e, n)
		case 7:
			e := g.intExpr(g.randInt(), 1, true).s
			return fmt.Sprintf("min(uint(%s), %d)", e, n-1)
		case 8:
			e := g.intExpr(g.randInt(), 1, true).s
			return fmt.Sprintf("max(min(int(%s), %d), 0)", e, n-1)
		}
	}
}

// ----------------------------------------------------------------------------
// Expressions

type expr struct {
	s string
	c bool // constant
}

// typed spells e so that it has its type even in a context without one.
func typed(e expr, t *typ) string {
	if e.c {
		return t.String() + "(" + e.s + ")"
	}
	return e.s
}

// intExpr returns an expression of integer type t. With nc, the
// expression is never constant.
func (g *gen) intExpr(t *typ, d int, nc bool) expr {
	if d <= 0 || g.chance(4) {
		return g.intLeaf(t, nc)
	}
	switch k := g.r.Intn(106); {
	case k >= 100:
		return g.rotate(t, d)
	case k < 35:
		ops := []string{"+", "-", "*", "&", "|", "^", "&^", "+", "-", "*"}
		a := g.intExpr(t, d-1, false)
		b := g.intExpr(t, d-1, a.c)
		return expr{s: "(" + a.s + " " + ops[g.r.Intn(len(ops))] + " " + b.s + ")"}
	case k < 50:
		a := g.intExpr(t, d-1, true)
		op := "<<"
		if g.chance(2) {
			op = ">>"
		}
		return expr{s: "(" + a.s + " " + op + " " + g.shiftCount(t, d-1) + ")"}
	case k < 62:
		a := g.intExpr(t, d-1, true)
		op := "/"
		if g.chance(2) {
			op = "%"
		}
		return expr{s: "(" + a.s + " " + op + " " + g.divisor(t) + ")"}
	case k < 70:
		return g.varDiv(t, d)
	case k < 76:
		a := g.intExpr(t, d-1, true)
		op := "-"
		if g.chance(2) {
			op = "^"
		}
		return expr{s: "(" + op + a.s + ")"}
	case k < 84:
		n := 2 + g.r.Intn(2)
		var args []string
		allConst := true
		for i := 0; i < n; i++ {
			a := g.intExpr(t, d-1, i == n-1 && allConst)
			allConst = allConst && a.c
			args = append(args, a.s)
		}
		fn := "min"
		if g.chance(2) {
			fn = "max"
		}
		return expr{s: fn + "(" + strings.Join(args, ", ") + ")"}
	case k < 94:
		if g.chance(5) {
			// From a float, through the range check.
			u := g.randFloat()
			f := g.floatExpr(u, d-1, true).s
			if g.chance(3) {
				if u == tFloat32 {
					f = "float64(" + f + ")"
				}
				return expr{s: t.String() + "(f2u(" + f + "))"}
			}
			return expr{s: t.String() + "(" + toInt(f, u) + ")"}
		}
		u := g.randInt()
		return expr{s: t.String() + "(" + g.intExpr(u, d-1, true).s + ")"}
	default:
		if c := g.pureCall(t); c != "" {
			return expr{s: c}
		}
		return g.intLeaf(t, nc)
	}
}

// rotate returns a rotation written with shifts, or something that looks
// like one but is not (an arithmetic right shift, a count that does not
// add up to the width, an unmasked variable count).
func (g *gen) rotate(t *typ, d int) expr {
	x := g.intExpr(t, d-1, true).s
	w := t.bits
	op := []string{"|", "^", "+"}[g.r.Intn(3)]
	switch g.r.Intn(4) {
	case 0:
		c := g.r.Intn(w + 1)
		return expr{s: fmt.Sprintf("((%s << %d) %s (%s >> %d))", x, c, op, x, w-c)}
	case 1:
		c := g.r.Intn(w + 1)
		return expr{s: fmt.Sprintf("((%s >> %d) %s (%s << %d))", x, c, op, x, max(w-c+g.r.Intn(3)-1, 0))}
	case 2:
		k := g.intExpr(g.randInt(), 1, true).s
		return expr{s: fmt.Sprintf("((%s << (uint(%s) & %d)) %s (%s >> ((%d - uint(%s)) & %d)))", x, k, w-1, op, x, w, k, w-1)}
	default:
		us := unsignedTypes()
		u := us[g.r.Intn(len(us))]
		k := g.intExpr(u, 1, true).s
		return expr{s: fmt.Sprintf("((%s << %s) %s (%s >> (%d - %s)))", x, k, op, x, w, k)}
	}
}

// shiftCount returns an unsigned or non-negative constant shift count.
func (g *gen) shiftCount(t *typ, d int) string {
	switch g.r.Intn(6) {
	case 0, 1:
		return strconv.Itoa(g.r.Intn(t.bits + 2))
	case 2:
		return strconv.Itoa(g.r.Intn(t.bits*2 + 8))
	case 3:
		return "uint8(" + g.intExpr(g.randInt(), d, true).s + ")"
	case 4:
		return "(uint(" + g.intExpr(g.randInt(), d, true).s + ") & 127)"
	default:
		us := unsignedTypes()
		u := us[g.r.Intn(len(us))]
		return g.intExpr(u, d, true).s
	}
}

// varDiv divides by a non-constant divisor that cannot be zero, with a
// dividend and divisor that cannot be MinInt and -1.
func (g *gen) varDiv(t *typ, d int) expr {
	op := "/"
	if g.chance(2) {
		op = "%"
	}
	a := g.intExpr(t, d-1, true).s
	b := g.intExpr(t, d-1, true).s
	if !t.signed {
		return expr{s: fmt.Sprintf("(%s %s (%s | %s))", a, op, b, g.nonzero(t))}
	}
	switch g.r.Intn(3) {
	case 0:
		return expr{s: fmt.Sprintf("((%s | 1) %s (%s | 1))", a, op, b)}
	case 1:
		return expr{s: fmt.Sprintf("((%s >> %d) %s (%s | 1))", a, 1+g.r.Intn(t.bits-1), op, b)}
	default:
		m := t.maxS() >> g.r.Intn(t.bits-1)
		return expr{s: fmt.Sprintf("(%s %s ((%s & %d) | 1))", a, op, b, m)}
	}
}

func (g *gen) nonzero(t *typ) string {
	for {
		c := g.unsignedConst(t)
		if c != 0 {
			return strconv.FormatUint(c, 10)
		}
	}
}

func (g *gen) intLeaf(t *typ, nc bool) expr {
	for {
		switch g.r.Intn(10) {
		case 0, 1:
			if !nc {
				return expr{s: g.constant(t), c: true}
			}
		case 2, 3, 4, 5:
			if p := g.place(t, false); p != "" {
				return expr{s: p}
			}
		case 6:
			if u := g.randInt(); u != t {
				if p := g.place(u, false); p != "" {
					return expr{s: t.String() + "(" + p + ")"}
				}
			}
		case 7:
			for _, v := range g.visible() {
				if v.t != nil && v.t.kind == kSlice && g.chance(2) {
					v.used = true
					return expr{s: t.String() + "(len(" + v.name + "))"}
				}
			}
		case 8:
			if c := g.pureCall(t); c != "" {
				return expr{s: c}
			}
		default:
			// A global of the type always exists.
			if p := g.place(t, false); p != "" {
				return expr{s: p}
			}
		}
	}
}

func (g *gen) boolExpr(d int, nc bool) expr {
	if d <= 0 || g.chance(5) {
		return g.boolLeaf(d, nc)
	}
	switch g.r.Intn(10) {
	case 0, 1:
		a := g.boolExpr(d-1, false)
		b := g.boolExpr(d-1, a.c)
		op := "&&"
		if g.chance(2) {
			op = "||"
		}
		return expr{s: "(" + a.s + " " + op + " " + b.s + ")"}
	case 2:
		return expr{s: "!" + g.boolExpr(d-1, true).s}
	default:
		return g.compare(d)
	}
}

func (g *gen) compare(d int) expr {
	if g.chance(6) {
		return g.floatCompare(d)
	}
	t := g.randInt()
	a := g.intExpr(t, d-1, false)
	b := g.intExpr(t, d-1, a.c)
	ops := []string{"==", "!=", "<", "<=", ">", ">="}
	return expr{s: "(" + a.s + " " + ops[g.r.Intn(len(ops))] + " " + b.s + ")"}
}

func (g *gen) boolLeaf(d int, nc bool) expr {
	for {
		switch g.r.Intn(8) {
		case 0:
			if !nc {
				return expr{s: g.constant(tBool), c: true}
			}
		case 1, 2, 3:
			if p := g.place(tBool, false); p != "" {
				return expr{s: p}
			}
		case 4:
			if c := g.pureCall(tBool); c != "" {
				return expr{s: c}
			}
		case 5:
			// Equality of structs or arrays.
			t := g.randType(false)
			if t.scalar() {
				continue
			}
			if p := g.place(t, false); p != "" {
				op := "=="
				if g.chance(2) {
					op = "!="
				}
				return expr{s: "(" + p + " " + op + " " + g.value(t, 1) + ")"}
			}
		default:
			return g.compare(min(d, 1))
		}
	}
}

// scalarExpr returns an expression of scalar type t.
func (g *gen) scalarExpr(t *typ, d int, nc bool) expr {
	switch t.kind {
	case kBool:
		return g.boolExpr(d, nc)
	case kFloat:
		return g.floatExpr(t, d, nc)
	}
	return g.intExpr(t, d, nc)
}

// value returns an expression of any non-slice type t, for a context that
// gives untyped constants their type.
func (g *gen) value(t *typ, d int) string {
	switch t.kind {
	case kInt, kBool, kFloat:
		return g.scalarExpr(t, d, false).s
	case kSlice:
		s, _, _ := g.sliceExpr(t.elem, 1)
		return s
	case kPtr:
		p, _ := g.addr(t.elem)
		return p
	}
	switch g.r.Intn(6) {
	case 0, 1:
		if p := g.place(t, false); p != "" {
			return p
		}
	case 2:
		if c := g.pureCall(t); c != "" {
			return c
		}
	case 3:
		return t.String() + "{}"
	}
	if d <= 0 {
		// Nested literals multiply; stop at a variable or the zero value.
		if p := g.place(t, false); p != "" {
			return p
		}
		return t.String() + "{}"
	}
	return g.literal(t, d)
}

func (g *gen) literal(t *typ, d int) string {
	var parts []string
	switch t.kind {
	case kArray:
		if t.n > 4 || (g.chance(3) && t.n > 1) {
			// Keyed, with a few elements set.
			for i := 0; i < t.n; i++ {
				if g.r.Intn(t.n) < 3 {
					parts = append(parts, fmt.Sprintf("%d: %s", i, g.value(t.elem, d-1)))
				}
			}
		} else {
			for i := 0; i < t.n; i++ {
				parts = append(parts, g.value(t.elem, d-1))
			}
		}
	case kStruct:
		if g.chance(2) {
			for _, f := range t.fields {
				parts = append(parts, g.value(f.t, d-1))
			}
		} else {
			for _, f := range t.fields {
				if g.chance(2) {
					parts = append(parts, f.name+": "+g.value(f.t, d-1))
				}
			}
		}
	}
	return t.String() + "{" + strings.Join(parts, ", ") + "}"
}

// sliceExpr returns a slice of elem with at least minLen elements, its
// length lower bound, and whether its elements belong to this function.
func (g *gen) sliceExpr(elem *typ, minLen int) (string, int, bool) {
	for {
		switch g.r.Intn(4) {
		case 0, 1:
			// Slice an array variable or array field.
			var cands []*variable
			for _, v := range g.visible() {
				if v.t != nil && !g.ranged[v] && hasArrayOf(v.t, elem, minLen) {
					cands = append(cands, v)
				}
			}
			for _, v := range g.globals {
				if hasArrayOf(v.t, elem, minLen) {
					cands = append(cands, v)
				}
			}
			if len(cands) == 0 {
				continue
			}
			v := cands[g.r.Intn(len(cands))]
			v.used = true
			v.sliced = true
			base, at := v.name, v.t
			if at.kind == kStruct {
				var fs []field
				for _, f := range at.fields {
					if f.t.kind == kArray && f.t.elem == elem && f.t.n >= minLen {
						fs = append(fs, f)
					}
				}
				f := fs[g.r.Intn(len(fs))]
				base, at = base+"."+f.name, f.t
			}
			lo := g.r.Intn(at.n - minLen + 1)
			hi := lo + minLen + g.r.Intn(at.n-lo-minLen+1)
			local := !v.global && v.level == g.cx.level
			return g.sliceSpelling(base, lo, hi, at.n), hi - lo, local
		case 2:
			var cands []*variable
			for _, v := range g.visible() {
				if v.t != nil && v.t.kind == kSlice && v.t.elem == elem && v.sliceLen >= minLen {
					cands = append(cands, v)
				}
			}
			if len(cands) == 0 {
				continue
			}
			v := cands[g.r.Intn(len(cands))]
			v.used = true
			lo := g.r.Intn(v.sliceLen - minLen + 1)
			hi := lo + minLen + g.r.Intn(v.sliceLen-lo-minLen+1)
			local := v.owned && v.level == g.cx.level
			if hi == v.sliceLen && g.chance(2) {
				if lo == 0 {
					return v.name, v.sliceLen, local
				}
				return fmt.Sprintf("%s[%d:]", v.name, lo), v.sliceLen - lo, local
			}
			return fmt.Sprintf("%s[%d:%d]", v.name, lo, hi), hi - lo, local
		default:
			n := minLen + g.r.Intn(3)
			var parts []string
			for i := 0; i < n; i++ {
				parts = append(parts, g.value(elem, 1-g.callDepth))
			}
			return "[]" + elem.String() + "{" + strings.Join(parts, ", ") + "}", n, true
		}
	}
}

func (g *gen) sliceSpelling(base string, lo, hi, n int) string {
	switch {
	case lo == 0 && hi == n:
		return base + "[:]"
	case lo == 0:
		return fmt.Sprintf("%s[:%d]", base, hi)
	case hi == n:
		return fmt.Sprintf("%s[%d:]", base, lo)
	}
	return fmt.Sprintf("%s[%d:%d]", base, lo, hi)
}

func hasArrayOf(t, elem *typ, minLen int) bool {
	if t.kind == kArray {
		return t.elem == elem && t.n >= minLen
	}
	if t.kind == kStruct {
		for _, f := range t.fields {
			if f.t.kind == kArray && f.t.elem == elem && f.t.n >= minLen {
				return true
			}
		}
	}
	return false
}

// ----------------------------------------------------------------------------
// Calls

// pureCall returns a call of a pure function or closure returning t, or "".
func (g *gen) pureCall(t *typ) string {
	return g.call(t, true)
}

func (g *gen) call(t *typ, pureOnly bool) string {
	if g.callDepth >= 2 {
		return ""
	}
	g.callDepth++
	defer func() { g.callDepth-- }()
	type cand struct {
		name   string
		params []*typ
		slices []int
		cost   int64
		v      *variable
		f      *fnInfo
	}
	var cands []cand
	for _, f := range g.funcs[:g.nfuncs] {
		if len(f.results) != 1 || (pureOnly && !f.pure) {
			continue
		}
		if f.results[0] != t && (f.tparam == nil || !g.canInstantiate(t)) {
			continue
		}
		if !f.pure && !g.cx.writeGlobal {
			continue
		}
		cands = append(cands, cand{f: f, cost: f.cost})
	}
	for _, v := range g.visible() {
		ci := v.closure
		if ci == nil || ci.result != t {
			continue
		}
		if !ci.pure && (pureOnly || v.level != g.cx.level || len(g.ranged) > 0) {
			continue
		}
		cands = append(cands, cand{name: v.name, params: ci.params, slices: make([]int, len(ci.params)), cost: ci.cost, v: v})
	}
	if len(cands) == 0 {
		return ""
	}
	c := cands[g.r.Intn(len(cands))]
	if g.cx.cost+g.cx.mult*(c.cost+1) > g.cx.budget {
		return ""
	}
	g.addCost(c.cost + 1)
	if c.f != nil {
		return g.callText(c.f, t)
	}
	c.v.used = true
	return c.name + "(" + g.args(c.params, c.slices) + ")"
}

// callText returns a call of function or method f with generated
// arguments. A generic function is instantiated with inst.
func (g *gen) callText(f *fnInfo, inst *typ) string {
	var params []*typ
	var lens []int
	for _, p := range f.params {
		params = append(params, g.subst(p.t, f.tparam, inst))
		lens = append(lens, p.sliceLen)
	}
	name := f.name
	if f.recv != nil {
		name = g.receiver(f) + "." + f.name
	}
	if f.tparam != nil {
		name += "[" + inst.String() + "]"
	}
	// A call statement's arguments count as nested in a call.
	if g.callDepth == 0 {
		g.callDepth++
		defer func() { g.callDepth-- }()
	}
	return name + "(" + g.args(params, lens) + ")"
}

// typeSetSpelling is the constraint of generated type parameters.
func typeSetSpelling() string {
	var parts []string
	for _, t := range genericSet() {
		parts = append(parts, "~"+t.String())
	}
	return strings.Join(parts, " | ")
}

// genericSet lists the types a type parameter may be instantiated with:
// the signed integers, so that every generated constant fits them all.
func genericSet() []*typ {
	var out []*typ
	for _, t := range intTypes {
		if t.signed {
			out = append(out, t)
		}
	}
	return out
}

// instFor returns a type to instantiate a generic function with: a
// random member of the type set, or within a generic function sometimes
// its own type parameter.
func (g *gen) instFor() *typ {
	if g.cx.tparam != nil && g.chance(3) {
		return g.cx.tparam
	}
	set := genericSet()
	return set[g.r.Intn(len(set))]
}

// canInstantiate reports whether a type parameter may be instantiated
// with t here.
func (g *gen) canInstantiate(t *typ) bool {
	return t.kind == kInt && t.signed && (!t.param || t == g.cx.tparam) && t != g.named
}

// subst replaces the type parameter tp in t with inst.
func (g *gen) subst(t, tp, inst *typ) *typ {
	switch {
	case tp == nil:
		return t
	case t == tp:
		return inst
	case t.kind == kSlice && t.elem == tp:
		if inst.param {
			return &typ{kind: kSlice, elem: inst}
		}
		return g.sliceOf(inst)
	}
	return t
}

// receiver returns a receiver for a call of method f. A pointer
// receiver must be addressable, and writable if f writes through it.
func (g *gen) receiver(f *fnInfo) string {
	s := f.recv.t
	if s.kind == kPtr {
		s = s.elem
		p, root := g.placeRoot(s, !f.pure)
		if p == "" {
			root = g.newGlobal(s)
			p = root.name
		}
		root.used = true
		root.sliced = true
		return p
	}
	if !g.chance(4) {
		if p := g.place(s, false); p != "" {
			return p
		}
	}
	return "(" + g.literal(s, 1) + ")"
}

func (g *gen) args(params []*typ, slices []int) string {
	var args []string
	for i, p := range params {
		if slices[i] < 0 {
			// The depth argument of a recursive function.
			if g.chance(2) {
				args = append(args, strconv.Itoa(g.r.Intn(maxRecDepth+1)))
			} else {
				args = append(args, fmt.Sprintf("int(%s & 7)", g.intExpr(g.randInt(), 1, true).s))
			}
			continue
		}
		if p.kind == kSlice {
			s, _, _ := g.sliceExpr(p.elem, slices[i])
			args = append(args, s)
			continue
		}
		d := 2
		if !p.scalar() || g.callDepth > 0 {
			d = 1
		}
		args = append(args, g.value(p, d))
	}
	return strings.Join(args, ", ")
}

// ----------------------------------------------------------------------------
// Functions

func (g *gen) function(i int) *fnInfo {
	f := &fnInfo{name: fmt.Sprintf("f%d", i), pure: g.chance(2)}
	g.lines = nil
	g.indent = 0
	g.cx = &ctx{results: nil, writeGlobal: !f.pure, mult: 1, budget: fnBudget}
	g.push()
	// A recursive function takes its depth first and returns an integer.
	rec := g.chance(5)
	var params []string
	addParam := func(v *variable) {
		g.declare(v)
		f.params = append(f.params, v)
		params = append(params, v.name+" "+v.t.String())
	}
	if rec {
		g.cx.budget /= maxRecDepth + 1
		addParam(&variable{name: g.name("n"), t: tInt, used: true, readonly: true, sliceLen: -1})
	} else if len(g.structs) > 0 && g.chance(4) {
		// A method, with a value or pointer receiver.
		s := g.structs[g.r.Intn(len(g.structs))]
		f.name = fmt.Sprintf("m%d", i) // f0... are field names
		f.recv = g.declare(&variable{name: g.name("r"), t: s, used: true})
		if g.chance(2) {
			f.recv.t = g.canon(&typ{kind: kPtr, elem: s})
		}
	} else if g.chance(5) {
		// A generic function over the signed integer types. Its first
		// result has the parameter type.
		f.tparam = &typ{kind: kInt, name: "T", bits: 8, signed: true, param: true}
		g.cx.tparam = f.tparam
	}
	np := g.r.Intn(5)
	if g.chance(6) {
		np = 5 + g.r.Intn(6) // more than fit in registers
	}
	for j := 0; j < np; j++ {
		t := g.randType(true)
		if f.tparam != nil && g.chance(4) {
			t = &typ{kind: kSlice, elem: f.tparam}
		}
		v := &variable{name: g.name("p"), t: t, used: true}
		if t.kind == kSlice {
			v.sliceLen = 1 + g.r.Intn(6)
		}
		addParam(v)
	}
	nr := 1 + g.r.Intn(2)
	if g.chance(8) {
		nr = 3 + g.r.Intn(2)
	}
	if rec {
		nr = 1
	}
	for j := 0; j < nr; j++ {
		t := g.randType(false)
		if rec {
			t = g.randInt()
		}
		if j == 0 && f.tparam != nil {
			t = f.tparam
		}
		f.results = append(f.results, t)
	}
	g.cx.results = f.results

	switch g.r.Intn(10) {
	case 0, 1, 2:
		g.line("//pu:noinline")
	case 3:
		g.line("//pu:inline")
	}
	// Named results, which deferred closures may change after a return.
	var named []*variable
	if !rec && g.chance(4) {
		for _, t := range f.results {
			named = append(named, g.declare(&variable{name: g.name("res"), t: t, used: true}))
		}
		g.cx.named = true
	}
	var res []string
	for i, t := range f.results {
		if named != nil {
			res = append(res, named[i].name+" "+t.String())
		} else {
			res = append(res, t.String())
		}
	}
	resStr := strings.Join(res, ", ")
	if len(res) > 1 || named != nil {
		resStr = "(" + resStr + ")"
	}
	switch {
	case f.recv != nil:
		g.line("func (%s %s) %s(%s) %s {", f.recv.name, f.recv.t, f.name, strings.Join(params, ", "), resStr)
	case f.tparam != nil:
		g.line("func %s[T %s](%s) %s {", f.name, typeSetSpelling(), strings.Join(params, ", "), resStr)
	default:
		g.line("func %s(%s) %s {", f.name, strings.Join(params, ", "), resStr)
	}
	g.indent++
	h := g.declare(&variable{name: g.name("h"), t: tUint64, used: true})
	g.cx.hash = h
	g.line("var %s uint64", h.name)
	if rec {
		g.line("if %s <= 0 {", f.params[0].name)
		g.line("\treturn %s", g.returnValues())
		g.line("}")
	}
	if named != nil || g.chance(6) {
		g.stmts(1 + g.r.Intn(2))
		g.deferStmt(named)
	}
	g.stmts(2 + g.r.Intn(5))
	var ret string
	switch {
	case rec:
		ret = g.selfCall(f)
	case named != nil && g.chance(2):
		// A bare return of the named results.
	default:
		ret = g.returnValues()
	}
	g.useAll()
	g.line("println(%q, %s)", f.name, h.name)
	g.line("return %s", ret)
	g.indent--
	g.line("}")
	g.line("")
	g.sc = g.sc.parent
	f.cost = g.cx.cost + 1
	if rec {
		f.cost *= maxRecDepth + 1
	}
	f.text = strings.Join(g.lines, "\n") + "\n"
	return f
}

// deferStmt defers a println, whose arguments are evaluated now, and a
// closure that runs after the return statement has set the named
// results and may change them.
func (g *gen) deferStmt(named []*variable) {
	t := g.concreteInt()
	g.line("defer println(\"deferred\", %s)", typed(g.intExpr(t, 2, false), t))
	if named == nil {
		return
	}
	g.line("defer func() {")
	for _, r := range named {
		switch r.t.kind {
		case kInt:
			if r.t.param {
				g.line("\t%s = %s*3 + 1", r.name, r.name)
			} else {
				g.line("\t%s = %s*3 + %s", r.name, r.name, g.constant(r.t))
			}
			g.line("\tprintln(\"defer sees\", %s)", r.name)
		case kBool:
			g.line("\t%s = !%s", r.name, r.name)
		default:
			g.line("\tprintln(\"defer sees\", %s)", leafOf(r.name, r.t))
		}
	}
	g.line("}()")
}

// maxRecDepth bounds the depth argument of recursive functions.
const maxRecDepth = 8

// selfCall returns the result expression of a recursive function: a tail
// call, or a call combined with a value as an accumulator.
func (g *gen) selfCall(f *fnInfo) string {
	var params []*typ
	var lens []int
	for _, p := range f.params[1:] {
		params = append(params, p.t)
		lens = append(lens, p.sliceLen)
	}
	n := f.params[0].name
	call := fmt.Sprintf("%s(%s - %d", f.name, n, 1+g.r.Intn(2))
	if a := g.args(params, lens); a != "" {
		call += ", " + a
	}
	call += ")"
	t := f.results[0]
	if !f.pure {
		// The order of a call and the reads in the same expression is
		// unspecified, so a call with side effects stands alone.
		return call
	}
	switch g.r.Intn(4) {
	case 0, 1:
		return call
	case 2:
		ops := []string{"+", "*", "^", "|", "&", "-"}
		return fmt.Sprintf("%s %s %s", g.intExpr(t, 2, false).s, ops[g.r.Intn(len(ops))], call)
	default:
		return fmt.Sprintf("%s + %s", call, g.intExpr(t, 2, false).s)
	}
}

// getMethod returns the Get method of t, which implements Ifc.
func (g *gen) getMethod(t *typ) string {
	g.lines = nil
	g.indent = 0
	g.nfuncs = 0
	g.cx = &ctx{mult: 1, budget: fnBudget / 4, results: []*typ{tInt}}
	g.push()
	r := g.declare(&variable{name: g.name("r"), t: t, used: true})
	x := g.declare(&variable{name: g.name("x"), t: tInt, used: true})
	g.line("func (%s %s) Get(%s int) int {", r.name, t, x.name)
	g.indent++
	g.stmts(1 + g.r.Intn(3))
	ret := fmt.Sprintf("int(%s)*%s + %s", leafOf(r.name, t), x.name, g.intExpr(tInt, 2, false).s)
	g.useAll()
	g.line("return %s", ret)
	g.indent--
	g.line("}")
	g.line("")
	g.sc = g.sc.parent
	return strings.Join(g.lines, "\n") + "\n"
}

// leafOf returns an integer expression read from a value p of type t: its
// first integer leaf, or 0.
func leafOf(p string, t *typ) string {
	switch t.kind {
	case kInt:
		return "int64(" + p + ")"
	case kFloat:
		return toInt(p, t)
	case kStruct:
		for _, f := range t.fields {
			if l := leafOf(p+"."+f.name, f.t); l != "0" {
				return l
			}
		}
	case kArray:
		return leafOf(p+"[0]", t.elem)
	}
	return "0"
}

// ifaceStmt converts a value to Ifc or any, calls Get through the
// interface, and switches on the dynamic type.
func (g *gen) ifaceStmt() bool {
	if g.ifc == nil || g.inGet || g.chance(3) {
		return g.anyStmt()
	}
	if g.cx.cost+g.cx.mult*3*fnBudget/4 > g.cx.budget {
		return g.anyStmt()
	}
	g.addCost(3 * fnBudget / 4) // at most three calls of Get
	t := g.implementers[g.r.Intn(len(g.implementers))]
	var val string
	if t == g.named {
		val = "N(" + g.intExpr(intTypes[2], 2, false).s + ")"
	} else {
		val = g.value(t, 1)
	}
	i := g.name("i")
	g.line("var %s Ifc = %s", i, val)
	g.line("println(%q, %s.Get(%s))", i, i, g.intExpr(tInt, 1, false).s)
	if g.chance(2) && g.assignStmt() {
		g.line("println(%q, %s.Get(%d))", i, i, g.r.Intn(9)-4)
	}
	v := g.name("v")
	g.line("switch %s := %s.(type) {", v, i)
	order := g.r.Perm(len(g.implementers))
	for _, k := range order[:1+g.r.Intn(len(order))] {
		u := g.implementers[k]
		g.line("case %s:", u)
		g.line("\tprintln(%q, %s)", u.name, leafOf(v, u))
		g.line("\t_ = %s", v)
	}
	if g.chance(2) {
		g.line("default:")
		g.line("\tprintln(\"other\")")
	}
	g.line("}")
	u := g.implementers[g.r.Intn(len(g.implementers))]
	w := g.name("w")
	g.line("if %s, ok := %s.(%s); ok {", w, i, u)
	g.line("\tprintln(\"is\", %s)", leafOf(w, u))
	g.line("\t_ = %s", w)
	g.line("} else {")
	g.line("\tprintln(\"is not\", ok)")
	g.line("}")
	return true
}

// anyStmt switches on the dynamic type of an integer in an any.
func (g *gen) anyStmt() bool {
	t := g.randInt()
	a, v := g.name("a"), g.name("v")
	g.line("var %s any = %s", a, typed(g.intExpr(t, 2, false), t))
	g.line("switch %s := %s.(type) {", v, a)
	seen := map[*typ]bool{}
	for _, k := range g.r.Perm(len(intTypes))[:1+g.r.Intn(4)] {
		seen[intTypes[k]] = true
	}
	seen[t] = g.chance(2) || seen[t]
	for _, u := range intTypes {
		if seen[u] {
			g.line("case %s:", u)
			g.line("\tprintln(%q, %s)", u.name, v)
		}
	}
	g.line("default:")
	g.line("\tprintln(\"other\", %s == nil)", v)
	g.line("}")
	return true
}

// useAll uses the innermost scope's unread variables without closing it,
// so that a function can end with its return statement.
func (g *gen) useAll() {
	g.pop()
	g.sc = &scope{parent: g.sc}
}

func (g *gen) returnValues() string {
	var vals []string
	for _, t := range g.cx.results {
		vals = append(vals, g.value(t, 3))
	}
	return strings.Join(vals, ", ")
}

func (g *gen) mainFunc() string {
	g.lines = nil
	g.indent = 0
	g.cx = &ctx{writeGlobal: true, mult: 1, budget: mainBudget, isMain: true}
	g.push()
	g.line("func main() {")
	g.indent++
	h := g.declare(&variable{name: g.name("h"), t: tUint64, used: true})
	g.cx.hash = h
	g.line("var %s uint64", h.name)
	g.stmts(3 + g.r.Intn(4))
	for _, f := range g.funcs {
		for k := 0; k < 1+g.r.Intn(2); k++ {
			if g.overBudget() {
				break
			}
			g.callAndPrint(f)
		}
	}
	for _, v := range g.globals {
		g.printLeaves(v.name, v.t)
	}
	g.pop()
	g.line("println(\"main\", %s)", h.name)
	g.indent--
	g.line("}")
	return strings.Join(g.lines, "\n") + "\n"
}

func (g *gen) callAndPrint(f *fnInfo) {
	g.addCost(f.cost + 1)
	var names []string
	for range f.results {
		names = append(names, g.name("r"))
	}
	inst := g.instFor()
	g.line("%s := %s", strings.Join(names, ", "), g.callText(f, inst))
	for i, t := range f.results {
		g.printLeaves(names[i], g.subst(t, f.tparam, inst))
	}
}

// printLeaves prints every scalar inside a value of type t.
func (g *gen) printLeaves(p string, t *typ) {
	var leaves []string
	var walk func(p string, t *typ)
	walk = func(p string, t *typ) {
		switch t.kind {
		case kInt, kBool:
			leaves = append(leaves, p)
		case kFloat:
			leaves = append(leaves, toInt(p, t))
		case kStruct:
			for _, f := range t.fields {
				walk(p+"."+f.name, f.t)
			}
		case kArray:
			for i := 0; i < t.n; i++ {
				walk(fmt.Sprintf("%s[%d]", p, i), t.elem)
			}
		}
	}
	walk(p, t)
	for len(leaves) > 0 {
		n := min(len(leaves), 8)
		g.line("println(%s)", strings.Join(leaves[:n], ", "))
		leaves = leaves[n:]
	}
}

func (g *gen) newGlobal(t *typ) *variable {
	v := &variable{name: g.name("g"), t: t, global: true, level: -1}
	g.globals = append(g.globals, v)
	out := &g.globalText
	switch {
	case t.scalar() && g.chance(3):
		fmt.Fprintf(out, "var %s %s\n", v.name, t)
	case t.scalar():
		fmt.Fprintf(out, "var %s %s = %s\n", v.name, t, g.constant(t))
	default:
		fmt.Fprintf(out, "var %s = %s\n", v.name, g.constLiteral(t))
	}
	return v
}

// addr returns the address of a variable, field or element of type elem,
// and whether that memory belongs to the current function.
func (g *gen) addr(elem *typ) (string, bool) {
	var cands []*variable
	for _, v := range g.visible() {
		if v.closure == nil && !v.readonly && !g.ranged[v] && reach(v.t, elem) {
			cands = append(cands, v)
		}
	}
	for _, v := range g.globals {
		if reach(v.t, elem) {
			cands = append(cands, v)
		}
	}
	var v *variable
	if len(cands) == 0 || g.chance(8) {
		v = g.newGlobal(elem)
	} else {
		v = cands[g.r.Intn(len(cands))]
	}
	v.used = true
	v.sliced = true
	owned := !v.global && v.level == g.cx.level && (!v.t.ref() || v.owned)
	return "&" + g.descend(v.name, v.t, elem, v), owned
}

// constLiteral is a composite literal of constants, for package-level
// initializers.
func (g *gen) constLiteral(t *typ) string {
	switch t.kind {
	case kInt, kBool, kFloat:
		return g.constant(t)
	case kArray:
		var parts []string
		for i := 0; i < t.n; i++ {
			parts = append(parts, g.constLiteral(t.elem))
		}
		return t.String() + "{" + strings.Join(parts, ", ") + "}"
	case kStruct:
		var parts []string
		for _, f := range t.fields {
			if g.chance(3) {
				continue
			}
			parts = append(parts, f.name+": "+g.constLiteral(f.t))
		}
		return t.String() + "{" + strings.Join(parts, ", ") + "}"
	}
	panic("constLiteral of " + t.String())
}

// ----------------------------------------------------------------------------
// Statements

func (g *gen) stmts(n int) {
	for i := 0; i < n && !g.overBudget() && len(g.lines) < maxLines; i++ {
		if g.stmt() {
			return
		}
	}
}

// block generates a braced block body of n statements in a new scope.
func (g *gen) block(n int) {
	g.indent++
	g.cx.depth++
	g.push()
	g.stmts(n)
	g.pop()
	g.cx.depth--
	g.indent--
}

// stmt generates one statement and reports whether it ends its block.
func (g *gen) stmt() bool {
	g.addCost(1)
	deep := g.cx.depth >= maxDepth
	for {
		switch k := g.r.Intn(145); {
		case k < 20:
			g.declStmt()
			return false
		case k < 38:
			if g.assignStmt() {
				return false
			}
		case k < 46:
			if !deep {
				g.ifStmt()
				return false
			}
		case k < 52:
			g.diamond()
			return false
		case k < 62:
			if !deep {
				g.loop()
				return false
			}
		case k < 66:
			if !deep {
				g.switchStmt()
				return false
			}
		case k < 73:
			if g.callStmt() {
				return false
			}
		case k < 77:
			g.printStmt()
			return false
		case k < 81:
			if g.cx.level < 2 && !deep {
				g.closure()
				return false
			}
		case k < 85:
			if g.guardedDiv() {
				return false
			}
		case k < 86:
			g.minDiv()
			return false
		case k < 92:
			if len(g.cx.loops) > 0 {
				g.branch()
				return false
			}
		case k < 94:
			if g.cx.depth > 0 && !g.cx.isMain {
				g.line("if %s {", g.boolExpr(2, true).s)
				g.indent++
				g.line("return %s", g.returnValues())
				g.indent--
				g.line("}")
				return false
			}
		case k < 100:
			if g.cx.depth > 0 && g.chance(8) {
				switch {
				case len(g.cx.loops) > 0 && (g.chance(2) || g.cx.isMain):
					g.line("break")
				case g.cx.isMain:
					continue
				default:
					g.line("return %s", g.returnValues())
				}
				return true
			}
		case k < 106:
			if !deep {
				g.facts()
				return false
			}
		case k < 112:
			if g.guardedLoad() {
				return false
			}
		case k < 116:
			if !deep && g.fillLoop() {
				return false
			}
		case k < 118:
			if g.maybeNil() {
				return false
			}
		case k < 124:
			if !deep && g.kernel() {
				return false
			}
		case k < 128:
			g.repeated()
			return false
		case k < 132:
			if g.ifaceStmt() {
				return false
			}
		case k < 136:
			g.floatStmt()
			return false
		case k < 139:
			g.stringStmt()
			return false
		case k < 142:
			g.aggStmt()
			return false
		default:
			g.aliasStmt()
			return false
		}
	}
}

// aliasStmt writes a local array through the array itself, a pointer to
// an element and a slice of it, interleaved with reads through the other
// views: what store-to-load forwarding must get right.
func (g *gen) aliasStmt() {
	et := g.concreteInt()
	n := 2 + g.r.Intn(5)
	a, p, s := g.name("arr"), g.name("p"), g.name("sl")
	k := g.r.Intn(n)
	lo := g.r.Intn(n)
	hi := lo + 1 + g.r.Intn(n-lo)
	g.line("{")
	g.indent++
	g.line("var %s [%d]%s", a, n, et)
	g.line("%s := &%s[%d]", p, a, k)
	g.line("%s := %s[%d:%d]", s, a, lo, hi)
	val := func() string { return typed(g.intExpr(et, 1, false), et) }
	for i, m := 0, 3+g.r.Intn(6); i < m; i++ {
		switch g.r.Intn(6) {
		case 0:
			g.line("%s[%d] = %s", a, g.r.Intn(n), val())
		case 1:
			g.line("*%s = %s", p, val())
		case 2:
			g.line("%s[%d] = %s", s, g.r.Intn(hi-lo), val())
		case 3:
			g.line("*%s += %s[%d]", p, s, g.r.Intn(hi-lo))
		case 4:
			var parts []string
			for j := 0; j < n; j++ {
				parts = append(parts, val())
			}
			g.line("%s = [%d]%s{%s}", a, n, et, strings.Join(parts, ", "))
		default:
			g.line("println(%s[%d], *%s, %s[%d], len(%s))", a, g.r.Intn(n), p, s, g.r.Intn(hi-lo), s)
		}
	}
	g.line("println(*%s, len(%s))", p, s)
	g.printLeaves(a, g.arrayOf(et, n))
	g.indent--
	g.line("}")
}

// aggStmt copies parts of a local aggregate onto other parts of it at
// constant paths, the accesses scalar replacement splits, sometimes with
// a pointer into it, and prints every leaf.
func (g *gen) aggStmt() {
	var t *typ
	if len(g.structs) > 0 && g.chance(2) {
		t = g.arrayOf(g.structs[g.r.Intn(len(g.structs))], 2+g.r.Intn(3))
	} else if len(g.structs) > 0 {
		t = g.structs[g.r.Intn(len(g.structs))]
	} else {
		t = g.arrayOf(g.concreteInt(), 2+g.r.Intn(4))
	}
	// Every path into t with constant indices, by type.
	type path struct {
		s string
		t *typ
	}
	var paths []path
	var walk func(s string, t *typ)
	walk = func(s string, t *typ) {
		paths = append(paths, path{s, t})
		switch t.kind {
		case kStruct:
			for _, f := range t.fields {
				walk(s+"."+f.name, f.t)
			}
		case kArray:
			for i := 0; i < t.n && i < 4; i++ {
				walk(fmt.Sprintf("%s[%d]", s, i), t.elem)
			}
		}
	}
	a, b := g.name("agg"), g.name("agg")
	walk(a, t)
	two := g.chance(2)
	if two {
		walk(b, t)
	}
	g.line("{")
	g.indent++
	g.line("var %s %s", a, t)
	if two {
		g.line("%s := %s", b, g.literal(t, 1))
	}
	var ptr, ptrPath string
	for i, n := 0, 3+g.r.Intn(6); i < n; i++ {
		p := paths[g.r.Intn(len(paths))]
		switch {
		case ptr == "" && p.s != a && p.s != b && g.chance(4):
			ptr, ptrPath = g.name("q"), p.s
			g.line("%s := &%s", ptr, p.s)
		case p.t.scalar():
			g.line("%s = %s", p.s, g.value(p.t, 1))
		case g.chance(5):
			// Clear part of it.
			g.line("%s = %s{}", p.s, p.t)
		default:
			// Copy from another path of the same type, possibly itself.
			var same []path
			for _, o := range paths {
				if o.t == p.t {
					same = append(same, o)
				}
			}
			g.line("%s = %s", p.s, same[g.r.Intn(len(same))].s)
		}
	}
	if ptr != "" {
		for _, p := range paths {
			if p.s == ptrPath {
				g.printLeaves("(*"+ptr+")", p.t)
				break
			}
		}
	}
	g.printLeaves(a, t)
	if two {
		g.printLeaves(b, t)
	}
	g.indent--
	g.line("}")
}

// A str is a package-level string variable and its contents.
type str struct {
	name string
	val  string
}

// randString returns a short string of ASCII, multi-byte UTF-8 and
// invalid bytes.
func (g *gen) randString() string {
	pieces := []string{"a", "b", "z", "0", " ", "é", "ü", "日本", "€", "\xff", "\xc3", "\xe2\x82", "𝄞", "\x00", "ab", "xyz"}
	var b strings.Builder
	for i, n := 0, g.r.Intn(8); i < n; i++ {
		b.WriteString(pieces[g.r.Intn(len(pieces))])
	}
	return b.String()
}

func (g *gen) stringVar() str {
	if len(g.strs) == 0 || (len(g.strs) < 6 && g.chance(3)) {
		s := str{name: g.name("s"), val: g.randString()}
		fmt.Fprintf(&g.globalText, "var %s = %s\n", s.name, strconv.Quote(s.val))
		g.strs = append(g.strs, s)
	}
	return g.strs[g.r.Intn(len(g.strs))]
}

// stringStmt reads strings: lengths, bytes, slices, comparisons, a byte
// loop, a rune loop and a switch.
func (g *gen) stringStmt() {
	s := g.stringVar()
	t := g.stringVar()
	n := len(s.val)
	acc := g.name("acc")
	g.line("{")
	g.indent++
	sub := s.name
	if n > 0 {
		lo := g.r.Intn(n + 1)
		hi := lo + g.r.Intn(n-lo+1)
		sub = fmt.Sprintf("%s[%d:%d]", s.name, lo, hi)
		g.line("println(len(%s), %s[%d], len(%s))", s.name, s.name, g.r.Intn(n), sub)
	}
	lit := strconv.Quote(g.randString())
	g.line("println(%s == %s, %s < %s, %s >= %s, %s != %s)", sub, t.name, s.name, t.name, sub, lit, t.name, lit)
	g.line("%s := 0", acc)
	switch g.r.Intn(3) {
	case 0:
		g.line("for i := 0; i < len(%s); i++ {", s.name)
		g.line("\t%s = %s*7 + int(%s[i])", acc, acc, s.name)
		g.line("}")
	case 1:
		g.line("for i, r := range %s {", sub)
		g.line("\t%s = %s*7 + i + int(r)", acc, acc)
		g.line("}")
	default:
		g.line("for _, r := range %s {", t.name)
		g.line("\tif r >= 0x80 {")
		g.line("\t\t%s++", acc)
		g.line("\t}")
		g.line("}")
	}
	g.line("println(%q, %s)", acc, acc)
	g.line("switch %s {", sub)
	g.line("case %s:", strconv.Quote(t.val))
	g.line("\tprintln(\"is t\")")
	if lit != strconv.Quote(t.val) {
		g.line("case %s:", lit)
		g.line("\tprintln(\"is lit\")")
	}
	g.line("default:")
	g.line("\tprintln(\"neither\")")
	g.line("}")
	g.indent--
	g.line("}")
	g.addCost(int64(4 * (n + len(t.val) + 4)))
}

// floatStmt computes with floating-point values that are exact (sums of
// products of small integers and dyadic fractions, so that rounding and
// fused multiply-add cannot change them) or special (zeros of either
// sign, infinities, NaN), and prints integer conversions of the exact
// ones and comparisons of all of them.
func (g *gen) floatStmt() {
	ft := "float64"
	small := []*typ{intTypes[0], intTypes[1], tUint8} // int8, int16, uint8
	if g.chance(3) {
		ft = "float32"
		small = []*typ{intTypes[0], tUint8}
	}
	leaf := func() string {
		switch g.r.Intn(4) {
		case 0:
			return fmt.Sprintf("%s(%.2f)", ft, float64(g.r.Intn(81)-40)/4)
		default:
			t := small[g.r.Intn(len(small))]
			return fmt.Sprintf("%s(%s)", ft, g.intExpr(t, 1, true).s)
		}
	}
	term := func() string {
		if g.chance(2) {
			return "(" + leaf() + " * " + leaf() + ")"
		}
		return leaf()
	}
	exact := func() string {
		e := term()
		for i, n := 0, g.r.Intn(3); i < n; i++ {
			op := " + "
			if g.chance(2) {
				op = " - "
			}
			e = "(" + e + op + term() + ")"
		}
		return e
	}
	// Exact values, a signed zero, and the special values.
	var vals []string
	for i, n := 0, 2+g.r.Intn(3); i < n; i++ {
		v := g.name("x")
		g.line("%s := %s", v, exact())
		vals = append(vals, v)
		g.line("println(%q, int64(%s), int64(%s / 4), int64(-%s / 3))", v, v, v, v)
	}
	z := g.name("z")
	g.line("%s := %s * 0", z, leaf()) // -0 when the leaf is negative
	g.line("println(1/%s < 0)", z)
	specials := []string{z, "-" + z, z + " / " + z, "1 / " + z, "-1 / " + z}
	all := append(append([]string{}, vals...), specials...)
	pick := func() string { return all[g.r.Intn(len(all))] }
	for i, n := 0, 1+g.r.Intn(3); i < n; i++ {
		a, b := pick(), pick()
		g.line("println(%s < %s, %s <= %s, %s == %s, %s != %s)", a, b, a, b, a, b, a, b)
	}
	// min and max, with the sign of a zero result.
	a, b := pick(), pick()
	fn := "min"
	if g.chance(2) {
		fn = "max"
	}
	m := g.name("m")
	g.line("%s := %s(%s, %s)", m, fn, a, b)
	g.line("println(%q, %s == %s, 1/%s < 0, %s > 0)", m, m, m, m, m)
	if len(vals) >= 2 {
		g.line("println(int64(%s(%s, %s)))", fn, vals[0], vals[1])
	}
	// A choice made by a float comparison: a conditional move must read
	// the unordered result correctly.
	r := g.name("r")
	t := g.concreteInt()
	g.line("%s := %s", r, typed(g.intExpr(t, 1, false), t))
	cmps := []string{"<", "<=", ">", ">=", "==", "!="}
	cond := fmt.Sprintf("%s %s %s", pick(), cmps[g.r.Intn(len(cmps))], pick())
	if g.chance(2) {
		cond = "!(" + cond + ")"
	}
	g.line("if %s {", cond)
	g.line("\t%s = %s", r, g.intExpr(t, 1, false).s)
	g.line("}")
	g.line("println(%q, %s)", r, r)
	if ft == "float64" && g.chance(2) {
		// Through float32 and back: small integers are exact in float32.
		x, y := g.intExpr(small[g.r.Intn(len(small))], 1, true).s, g.intExpr(small[g.r.Intn(len(small))], 1, true).s
		g.line("println(int64(float32(float64(%s))), int64(float64(float32(float64(%s)) * 0.5)))", x, y)
	}
}

// repeated evaluates the same expression twice with a store in between,
// and similar expressions at different types: what CSE must and must not
// merge.
func (g *gen) repeated() {
	t := g.randInt()
	e := g.intExpr(t, 3, true).s
	a, b := g.name("v"), g.name("v")
	g.line("%s := %s", a, e)
	if !g.chance(4) {
		if !g.assignStmt() {
			g.callStmt()
		}
	}
	g.line("%s := %s == %s", b, e, a)
	g.line("println(%q, %s, %s)", a, a, b)
}

// kernel emits one of a few classic loops over an array or slice of
// integers: the shapes bounds-check elimination and induction variable
// analysis are written for.
func (g *gen) kernel() bool {
	var cands []*variable
	for _, v := range g.visible() {
		if v.t == nil || g.ranged[v] || (v.t.kind != kSlice && v.t.kind != kArray) || v.t.elem.kind != kInt {
			continue
		}
		if (v.t.kind == kSlice && g.canWriteElems(v)) || (v.t.kind == kArray && g.canWriteRoot(v)) {
			cands = append(cands, v)
		}
	}
	if len(cands) == 0 {
		return false
	}
	s := cands[g.r.Intn(len(cands))]
	n := s.sliceLen + 4
	if s.t.kind == kArray {
		n = s.t.n
	}
	if g.cx.mult*int64(n*n) > 4000 {
		return false
	}
	s.used = true
	g.addCost(int64(n * n))
	et := s.t.elem
	S := s.name
	h := g.cx.hash
	acc := g.name("acc")
	i, j, x := g.name("i"), g.name("j"), g.name("x")
	g.line("{")
	g.indent++
	switch g.r.Intn(8) {
	case 0:
		// Sum over a prefix whose length is clamped to the length.
		g.line("%s := min(%s, len(%s))", x, g.intExpr(tInt, 2, true).s, S)
		g.line("var %s %s", acc, et)
		g.line("for %s := 0; %s < %s; %s++ {", i, i, x, i)
		g.line("\t%s += %s[%s] * %s[%s-1-%s]", acc, S, i, S, x, i)
		g.line("}")
		g.line("println(%q, %s, %s)", acc, acc, x)
	case 1:
		// Reverse in place.
		g.line("for %s, %s := 0, len(%s)-1; %s < %s; %s, %s = %s+1, %s-1 {", i, j, S, i, j, i, j, i, j)
		g.line("\t%s[%s], %s[%s] = %s[%s], %s[%s]", S, i, S, j, S, j, S, i)
		g.line("}")
	case 2:
		// Binary search after an insertion sort.
		g.insertionSort(S, i, j, x)
		g.line("%s, %s := 0, len(%s)", i, j, S)
		g.line("%s := %s", x, typed(g.intExpr(et, 1, false), et))
		g.line("for %s < %s {", i, j)
		g.line("\tm := int(uint(%s+%s) >> 1)", i, j)
		g.line("\tif %s[m] < %s {", S, x)
		g.line("\t\t%s = m + 1", i)
		g.line("\t} else {")
		g.line("\t\t%s = m", j)
		g.line("\t}")
		g.line("}")
		g.line("println(\"search\", %s, %s)", i, x)
	case 3:
		// Prefix sums.
		g.line("for %s := 1; %s < len(%s); %s++ {", i, i, S, i)
		g.line("\t%s[%s] += %s[%s-1]", S, i, S, i)
		g.line("}")
	case 4:
		// Count and select, which becomes conditional moves.
		g.line("%s := %s", x, typed(g.intExpr(et, 1, false), et))
		g.line("%s, %s := 0, 0", acc, j)
		g.line("for %s, v := range %s {", i, S)
		g.line("\tif v > %s {", x)
		g.line("\t\t%s++", acc)
		g.line("\t}")
		g.line("\tif v < %s[%s] {", S, j)
		g.line("\t\t%s = %s", j, i)
		g.line("\t}")
		g.line("}")
		g.line("println(%q, %s, %s)", acc, acc, j)
	case 5:
		g.insertionSort(S, i, j, x)
	case 6:
		// A stride-2 walk reading pairs, and a walk down from the end.
		g.line("var %s %s", acc, et)
		g.line("for %s := 1; %s < len(%s); %s += 2 {", i, i, S, i)
		g.line("\t%s ^= %s[%s-1] - %s[%s]", acc, S, i, S, i)
		g.line("}")
		g.line("for %s := len(%s); %s > 0; %s-- {", i, S, i, i)
		g.line("\t%s = %s*3 + %s[%s-1]", acc, acc, S, i)
		g.line("}")
		g.line("println(%q, %s)", acc, acc)
	default:
		// Shift elements left by a variable distance.
		g.line("%s := int(uint(%s) %% uint(len(%s)))", x, g.intExpr(g.randInt(), 1, true).s, S)
		g.line("for %s := %s; %s < len(%s); %s++ {", i, x, i, S, i)
		g.line("\t%s[%s-%s] = %s[%s]", S, i, x, S, i)
		g.line("}")
	}
	if h != nil && g.canWriteRoot(h) {
		g.line("for _, v := range %s {", S)
		g.line("\t%s = %s*31 + uint64(v)", h.name, h.name)
		g.line("}")
	}
	g.indent--
	g.line("}")
	return true
}

func (g *gen) insertionSort(s, i, j, x string) {
	g.line("for %s := 1; %s < len(%s); %s++ {", i, i, s, i)
	g.line("\t%s := %s[%s]", x, s, i)
	g.line("\t%s := %s - 1", j, i)
	g.line("\tfor %s >= 0 && %s[%s] > %s {", j, s, j, x)
	g.line("\t\t%s[%s+1] = %s[%s]", s, j, s, j)
	g.line("\t\t%s--", j)
	g.line("\t}")
	g.line("\t%s[%s+1] = %s", s, j, x)
	g.line("}")
}

// facts compares related values in nested conditions, so that the
// prove pass can use one comparison to decide another. The offsets
// reach the ends of the type's range.
func (g *gen) facts() {
	t := g.randInt()
	a := g.place(t, false)
	if a == "" {
		a = g.intExpr(t, 1, true).s // a type parameter with no variables
	}
	b := g.intExpr(t, 1, true).s
	off := func() string {
		if g.chance(3) {
			return ""
		}
		if t.signed {
			return fmt.Sprintf(" + %d", g.r.Intn(5)-2)
		}
		return fmt.Sprintf(" + %d", g.r.Intn(3))
	}
	ops := []string{"<", "<=", ">", ">=", "==", "!="}
	op := func() string { return ops[g.r.Intn(len(ops))] }
	g.line("if %s %s %s%s {", a, op(), b, off())
	g.indent++
	for i, n := 0, 1+g.r.Intn(2); i < n; i++ {
		c := []string{a, b, a + off(), b + off(), g.constant(t)}
		x, y := c[g.r.Intn(len(c))], c[g.r.Intn(len(c))]
		if x == y {
			y = b
		}
		if g.chance(2) && !strings.Contains(x+y, " + ") {
			g.line("println(%s %s %s, %s %s %s)", x, op(), y, a, op(), b)
			continue
		}
		g.line("if %s %s %s {", x, op(), y)
		g.line("\tprintln(%q, %s)", g.name("t"), typed(expr{s: a}, t))
		g.line("} else {")
		g.line("\tprintln(%q, %s)", g.name("f"), typed(expr{s: b}, t))
		g.line("}")
	}
	g.indent--
	g.line("} else if %s %s %s {", b, op(), a)
	g.line("\tprintln(%s %s %s)", a, op(), b)
	g.line("}")
}

// guardedLoad reads an element or divides only under a condition that
// makes it safe, the shape branch elimination must not speculate.
func (g *gen) guardedLoad() bool {
	var cands []*variable
	for _, v := range g.visible() {
		if v.t != nil && (v.t.kind == kSlice || v.t.kind == kArray) && v.t.elem.kind == kInt {
			cands = append(cands, v)
		}
	}
	t := g.randInt()
	k := g.name("k")
	r := &variable{name: g.name("v"), t: t}
	switch {
	case len(cands) > 0 && g.chance(3):
		s := cands[g.r.Intn(len(cands))]
		s.used = true
		r.t = s.t.elem
		g.line("%s := %s", k, g.intExpr(tInt, 2, true).s)
		g.line("%s := %s", r.name, typed(expr{s: g.constant(r.t), c: true}, r.t))
		if g.chance(2) {
			g.line("if %s >= 0 && %s < len(%s) {", k, k, s.name)
		} else {
			g.line("if uint(%s) < uint(len(%s)) {", k, s.name)
		}
		g.line("\t%s = %s[%s]", r.name, s.name, k)
		g.line("}")
	case g.chance(2):
		g.line("%s := %s", k, g.intExpr(t, 2, true).s)
		g.line("%s := %s", r.name, typed(g.intExpr(t, 1, false), t))
		cond := fmt.Sprintf("%s != 0", k)
		if t.signed {
			cond += fmt.Sprintf(" && %s != -1", k)
		}
		g.line("if %s {", cond)
		op := "/"
		if g.chance(2) {
			op = "%"
		}
		g.line("\t%s = %s %s %s", r.name, g.intExpr(t, 1, true).s, op, k)
		g.line("}")
	default:
		return false
	}
	g.declare(r)
	return true
}

// fillLoop stores the same value into a range of an array or slice, the
// loop the optimiser turns into a block fill.
func (g *gen) fillLoop() bool {
	var cands []*variable
	for _, v := range g.visible() {
		if v.t == nil || g.ranged[v] || (v.t.kind != kSlice && v.t.kind != kArray) {
			continue
		}
		if v.t.elem.kind != kInt {
			continue
		}
		if (v.t.kind == kSlice && g.canWriteElems(v)) || (v.t.kind == kArray && g.canWriteRoot(v)) {
			cands = append(cands, v)
		}
	}
	if len(cands) == 0 {
		return false
	}
	s := cands[g.r.Intn(len(cands))]
	s.used = true
	val := g.constant(s.t.elem)
	if g.chance(2) {
		val = g.intExpr(s.t.elem, 1, true).s
	}
	n := s.sliceLen
	if s.t.kind == kArray {
		n = s.t.n
	}
	i := g.name("i")
	switch g.r.Intn(3) {
	case 0:
		g.line("for %s := range %s {", i, s.name)
	case 1:
		lo := g.r.Intn(n)
		hi := lo + g.r.Intn(n-lo+1)
		g.line("for %s := %d; %s < %d; %s++ {", i, lo, i, hi, i)
	default:
		g.line("for %s := 0; %s < len(%s); %s++ {", i, i, s.name, i)
	}
	g.line("\t%s[%s] = %s", s.name, i, val)
	g.line("}")
	g.addCost(int64(n) + 4)
	return true
}

// maybeNil loads through a pointer that is nil on some paths, guarded by
// a nil check.
func (g *gen) maybeNil() bool {
	t := g.concreteInt()
	p := g.name("q")
	g.line("var %s *%s", p, t)
	g.line("if %s {", g.boolExpr(2, true).s)
	a, _ := g.addr(t)
	g.line("\t%s = %s", p, a)
	g.line("}")
	r := &variable{name: g.name("v"), t: t}
	g.line("%s := %s", r.name, typed(expr{s: g.constant(t), c: true}, t))
	g.line("if %s != nil {", p)
	g.line("\t%s = *%s", r.name, p)
	g.line("}")
	g.declare(r)
	return true
}

func (g *gen) declStmt() {
	t := g.randType(true)
	// The initialiser may read the variable this one hides.
	v := &variable{name: g.shadowName(), t: t}
	switch t.kind {
	case kInt, kBool, kFloat:
		switch g.r.Intn(5) {
		case 0:
			g.line("var %s %s", v.name, t)
		case 1:
			g.line("var %s %s = %s", v.name, t, g.scalarExpr(t, 3, false).s)
		case 2:
			// A constant the optimiser can propagate.
			g.line("var %s %s = %s", v.name, t, g.constant(t))
		default:
			g.line("%s := %s", v.name, typed(g.scalarExpr(t, 3, false), t))
		}
	case kSlice:
		s, n, local := g.sliceExpr(t.elem, 1)
		v.sliceLen, v.owned = n, local
		g.line("%s := %s", v.name, s)
	case kPtr:
		p, local := g.addr(t.elem)
		v.owned = local
		g.line("%s := %s", v.name, p)
	default:
		if g.chance(3) {
			g.line("var %s %s", v.name, t)
		} else {
			g.line("%s := %s", v.name, g.value(t, 2))
		}
	}
	g.declare(v)
}

func (g *gen) assignStmt() bool {
	var t *typ
	switch {
	case g.chance(6):
		t = g.randType(false)
	case g.chance(8):
		t = tBool
	case g.chance(8):
		t = g.randFloat()
	default:
		t = g.randInt()
	}
	p := g.place(t, true)
	if p == "" {
		return false
	}
	if t.kind == kFloat && g.chance(2) {
		op := []string{"+=", "-=", "*=", "/="}[g.r.Intn(4)]
		e := g.floatExpr(t, 2, op == "/=")
		g.line("%s %s %s", p, op, e.s)
		return true
	}
	if t.kind != kInt {
		g.line("%s = %s", p, g.value(t, 3))
		return true
	}
	switch g.r.Intn(12) {
	case 0, 1, 2, 3:
		g.line("%s = %s", p, g.intExpr(t, 3, false).s)
	case 4:
		if g.chance(2) {
			g.line("%s++", p)
		} else {
			g.line("%s--", p)
		}
	case 5:
		op := "<<="
		if g.chance(2) {
			op = ">>="
		}
		g.line("%s %s %s", p, op, g.shiftCount(t, 1))
	case 6:
		op := "/="
		if g.chance(2) {
			op = "%="
		}
		g.line("%s %s %s", p, op, g.divisor(t))
	default:
		ops := []string{"+=", "-=", "*=", "&=", "|=", "^=", "&^="}
		g.line("%s %s %s", p, ops[g.r.Intn(len(ops))], g.intExpr(t, 2, false).s)
	}
	return true
}

func (g *gen) ifStmt() {
	g.line("if %s {", g.boolExpr(3, true).s)
	g.block(1 + g.r.Intn(3))
	for g.chance(3) {
		g.line("} else if %s {", g.boolExpr(2, true).s)
		g.block(1 + g.r.Intn(2))
	}
	if g.chance(2) {
		g.line("} else {")
		g.block(1 + g.r.Intn(3))
	}
	g.line("}")
}

// diamond computes a value on two paths, the shape branch elimination
// turns into a conditional move.
func (g *gen) diamond() {
	t := g.randInt()
	switch g.r.Intn(6) {
	case 0:
		t = tBool
	case 1:
		t = g.randFloat()
	}
	v := &variable{name: g.name("v"), t: t}
	if g.chance(2) {
		g.line("var %s %s", v.name, t)
		g.line("if %s {", g.boolExpr(2, true).s)
		g.line("\t%s = %s", v.name, g.scalarExpr(t, 2, false).s)
		g.line("} else {")
		g.line("\t%s = %s", v.name, g.scalarExpr(t, 2, false).s)
		g.line("}")
	} else {
		g.line("%s := %s", v.name, typed(g.scalarExpr(t, 2, false), t))
		g.line("if %s {", g.boolExpr(2, true).s)
		g.line("\t%s = %s", v.name, g.scalarExpr(t, 2, false).s)
		g.line("}")
	}
	g.declare(v)
	if g.chance(3) {
		v.used = true
		g.line("println(%q, %s)", v.name, leafOrBool(v.name, t))
	}
}

func (g *gen) printStmt() {
	var args []string
	for i, n := 0, 1+g.r.Intn(4); i < n; i++ {
		t := g.randInt()
		switch g.r.Intn(6) {
		case 0:
			t = tBool
		case 1:
			u := g.randFloat()
			args = append(args, toInt(g.floatExpr(u, 3, false).s, u))
			continue
		}
		args = append(args, typed(g.scalarExpr(t, 3, false), t))
	}
	g.line("println(%s)", strings.Join(args, ", "))
}

// guardedDiv divides by a non-constant divisor under a guard against
// zero and MinInt / -1.
func (g *gen) guardedDiv() bool {
	t := g.concreteInt() // the guard spells the type's minimum
	var target *variable
	for _, v := range g.visible() {
		if v.t == t && g.canWriteRoot(v) {
			target = v
		}
	}
	if target == nil {
		return false
	}
	d := g.name("d")
	op := "/"
	if g.chance(2) {
		op = "%"
	}
	e := t.String() + "(-1)"
	if !t.signed || !g.chance(4) {
		e = g.intExpr(t, 2, true).s
	}
	x := g.place(t, false) // the dividend; reading it has no side effects
	if t.signed {
		g.line("if %s := %s; %s != 0 && (%s != -1 || %s != %s) {", d, e, d, d, x, t.minLit())
	} else {
		g.line("if %s := %s; %s != 0 {", d, e, d)
	}
	g.line("\t%s = %s %s %s", target.name, x, op, d)
	g.line("}")
	return true
}

// minDiv divides MinInt by -1, which Go and Plutonium define, only when
// the operands are exactly those values.
func (g *gen) minDiv() {
	t := intTypes[g.r.Intn(4)] // signed sized types
	if g.chance(3) {
		t = tInt
	}
	a, d := g.name("m"), g.name("d")
	g.line("{")
	ae := t.String() + "(" + t.minLit() + ")"
	if g.chance(2) {
		ae = typed(g.intExpr(t, 1, false), t)
	}
	de := t.String() + "(-1)"
	if g.chance(2) {
		de = typed(g.intExpr(t, 1, false), t)
	}
	g.line("\t%s := %s", a, ae)
	g.line("\t%s := %s", d, de)
	g.line("\tif %s == %s && %s == -1 {", a, t.minLit(), d)
	g.line("\t\tprintln(\"mindiv\", %s / %s, %s %% %s)", a, d, a, d)
	g.line("\t}")
	g.line("}")
}

func (g *gen) branch() {
	label := ""
	if len(g.cx.loops) > 1 && g.chance(3) {
		l := g.cx.loops[g.r.Intn(len(g.cx.loops))]
		l.labelUsed = true
		label = " " + l.label
	}
	kw := "break"
	if g.chance(2) {
		kw = "continue"
	}
	g.line("if %s {", g.boolExpr(2, true).s)
	g.line("\t%s%s", kw, label)
	g.line("}")
}

func (g *gen) switchStmt() {
	if g.chance(3) {
		g.line("switch {")
		for i, n := 0, 1+g.r.Intn(3); i < n; i++ {
			g.line("case %s:", g.boolExpr(2, true).s)
			g.caseBody(i < n-1)
		}
		if g.chance(2) {
			g.line("default:")
			g.caseBody(false)
		}
		g.line("}")
		return
	}
	t := g.randInt()
	g.line("switch %s {", g.intExpr(t, 2, true).s)
	seen := map[string]bool{}
	var heads []string
	for i, n := 0, 1+g.r.Intn(4); i < n; i++ {
		var vals []string
		for j, m := 0, 1+g.r.Intn(2); j < m; j++ {
			c := g.constant(t)
			if !t.signed && g.chance(2) {
				c = strconv.Itoa(g.r.Intn(8))
			} else if t.signed && g.chance(2) {
				c = strconv.Itoa(g.r.Intn(9) - 4)
			}
			if !seen[c] {
				seen[c] = true
				vals = append(vals, c)
			}
		}
		if len(vals) > 0 {
			heads = append(heads, "case "+strings.Join(vals, ", ")+":")
		}
	}
	if g.chance(2) {
		heads = slices.Insert(heads, g.r.Intn(len(heads)+1), "default:")
	}
	for i, h := range heads {
		g.line("%s", h)
		g.caseBody(i < len(heads)-1)
	}
	g.line("}")
}

func (g *gen) caseBody(canFall bool) {
	g.indent++
	g.cx.depth++
	g.push()
	n := g.r.Intn(4)
	ended := false
	for i := 0; i < n && !g.overBudget() && !ended && len(g.lines) < maxLines; i++ {
		ended = g.stmt()
	}
	g.pop()
	if canFall && !ended && g.chance(4) {
		g.line("fallthrough")
	}
	g.cx.depth--
	g.indent--
}

// ----------------------------------------------------------------------------
// Loops

func (g *gen) loop() {
	g.loopStart = len(g.lines)
	switch g.r.Intn(10) {
	case 0, 1, 2:
		g.counterLoop()
	case 3, 4:
		g.rangeInt()
	case 5, 6:
		g.rangeArray()
	case 7:
		g.lenLoop()
	case 8:
		g.shiftLoop()
	default:
		g.breakLoop()
	}
}

// loopBody generates the body of a loop that runs at most trips times.
// header is the index of the loop's first line, where a label goes.
func (g *gen) loopBody(trips int64, vars ...*variable) {
	l := &loopInfo{label: g.name("L")}
	header := g.loopStart
	g.cx.loops = append(g.cx.loops, l)
	saved := g.cx.mult
	g.cx.mult *= max(trips, 1)
	g.indent++
	g.cx.depth++
	g.push()
	for _, v := range vars {
		g.declare(v)
	}
	g.stmts(1 + g.r.Intn(3))
	g.pop()
	g.cx.depth--
	g.indent--
	g.cx.mult = saved
	g.cx.loops = g.cx.loops[:len(g.cx.loops)-1]
	g.line("}")
	if l.labelUsed {
		g.lines = slices.Insert(g.lines, header, strings.Repeat("\t", g.indent)+l.label+":")
	}
}

// tripLimit keeps nested loops within the budget.
func (g *gen) tripLimit() int64 {
	switch {
	case g.cx.mult >= 256:
		return 2
	case g.cx.mult >= 32:
		return 6
	}
	return 14
}

func (g *gen) counterLoop() {
	t := tInt
	if g.chance(2) {
		t = g.randInt()
	}
	step := int64(1 + g.r.Intn(3))
	trips := int64(g.r.Intn(int(g.tripLimit()) + 1))
	var lo int64
	if t.signed {
		lo = int64(g.r.Intn(16) - 5)
	} else {
		lo = int64(g.r.Intn(10))
	}
	hi := lo + trips*step
	i := &variable{name: g.name("i"), t: t, readonly: true, used: true, hasRange: true}
	init := func(v int64) string {
		if t == tInt {
			return strconv.FormatInt(v, 10)
		}
		return fmt.Sprintf("%s(%d)", t, v)
	}
	post := func(op string) string {
		if step == 1 {
			return i.name + op + op
		}
		return fmt.Sprintf("%s %s= %d", i.name, op, step)
	}
	if g.chance(2) {
		// Counting up from lo; the values are lo, lo+step, ..., last.
		var cond string
		var last int64
		switch g.r.Intn(3) {
		case 0:
			bound := max(hi-int64(g.r.Intn(int(step))), lo)
			cond = fmt.Sprintf("%s < %d", i.name, bound)
			last = lo + (bound-lo-1)/step*step
		case 1:
			cond = fmt.Sprintf("%s <= %d", i.name, hi)
			last = hi
		default:
			cond = fmt.Sprintf("%s != %d", i.name, hi)
			last = hi - step
		}
		i.lo, i.hi = lo, max(last, lo)
		g.line("for %s := %s; %s; %s {", i.name, init(lo), cond, post("+"))
	} else {
		// Counting down from hi to lo.
		if !t.signed && lo < step {
			lo += step
			hi += step
		}
		var cond string
		var last int64
		switch g.r.Intn(3) {
		case 0:
			cond = fmt.Sprintf("%s > %d", i.name, lo)
			last = lo + step
		case 1:
			cond = fmt.Sprintf("%s >= %d", i.name, lo)
			last = lo
		default:
			cond = fmt.Sprintf("%s != %d", i.name, lo)
			last = lo + step
		}
		i.lo, i.hi = min(last, hi), hi
		g.line("for %s := %s; %s; %s {", i.name, init(hi), cond, post("-"))
	}
	g.loopBody(trips+1, i)
}

func (g *gen) rangeInt() {
	limit := g.tripLimit()
	if g.chance(2) {
		n := int64(g.r.Intn(int(limit) + 1))
		if g.chance(4) {
			g.line("for range %d {", n)
			g.loopBody(n)
			return
		}
		i := &variable{name: g.name("i"), t: tInt, readonly: true, hasRange: true, lo: 0, hi: max(n-1, 0)}
		g.line("for %s := range %d {", i.name, n)
		g.loopBody(n, i)
		return
	}
	t := g.concreteInt() // ranging over a type parameter needs a core type
	mask := int64(1)
	for mask*2 <= limit+1 {
		mask *= 2
	}
	mask--
	i := &variable{name: g.name("i"), t: t, readonly: true, hasRange: true, lo: 0, hi: mask}
	g.line("for %s := range %s & %d {", i.name, g.intExpr(t, 2, true).s, mask)
	g.loopBody(mask+1, i)
}

func (g *gen) rangeArray() {
	type cand struct {
		v    *variable
		path string
		t    *typ
	}
	var cands []cand
	for _, v := range append(g.visible(), g.globals...) {
		if v.t == nil {
			continue
		}
		switch v.t.kind {
		case kArray, kSlice:
			cands = append(cands, cand{v, v.name, v.t})
		case kStruct:
			for _, f := range v.t.fields {
				if f.t.kind == kArray {
					cands = append(cands, cand{v, v.name + "." + f.name, f.t})
				}
			}
		}
	}
	if len(cands) == 0 {
		g.rangeInt()
		return
	}
	c := cands[g.r.Intn(len(cands))]
	n := c.t.n
	if c.t.kind == kSlice {
		n = c.v.sliceLen + 4 // a guess; slice parameters can be longer
	}
	if int64(n) > g.tripLimit()*2 {
		g.rangeInt()
		return
	}
	c.v.used = true
	key := &variable{name: g.name("k"), t: tInt, readonly: true, hasRange: c.t.kind == kArray, lo: 0, hi: int64(n - 1)}
	if c.t.kind == kSlice {
		key.boundSlice = c.v
	}
	val := &variable{name: g.name("e"), t: c.t.elem, readonly: true}
	// Go ranges over a copy of an array; keep the array unchanged while
	// a value variable is live, unless asked not to.
	isArray := c.t.kind == kArray
	withValue := !isArray || g.opt.RangeWrites || (!c.v.global && !c.v.sliced && c.v.level == g.cx.level)
	switch {
	case withValue && g.chance(3):
		g.line("for _, %s := range %s {", val.name, c.path)
		g.withRanged(c.v, isArray, func() { g.loopBody(int64(n), val) })
	case withValue && g.chance(2):
		g.line("for %s, %s := range %s {", key.name, val.name, c.path)
		g.withRanged(c.v, isArray, func() { g.loopBody(int64(n), key, val) })
	default:
		g.line("for %s := range %s {", key.name, c.path)
		g.loopBody(int64(n), key)
	}
}

func (g *gen) withRanged(v *variable, isArray bool, body func()) {
	if !isArray || g.opt.RangeWrites || g.ranged[v] {
		body()
		return
	}
	g.ranged[v] = true
	body()
	delete(g.ranged, v)
}

// lenLoop indexes a slice or array with a counter bounded by its length.
func (g *gen) lenLoop() {
	var cands []*variable
	for _, v := range g.visible() {
		if v.t != nil && (v.t.kind == kSlice || v.t.kind == kArray) {
			cands = append(cands, v)
		}
	}
	if len(cands) == 0 {
		g.counterLoop()
		return
	}
	s := cands[g.r.Intn(len(cands))]
	i := &variable{name: g.name("i"), t: tInt, readonly: true, used: true}
	n := int64(s.sliceLen + 4)
	if s.t.kind == kArray {
		n = int64(s.t.n)
		i.hasRange, i.lo, i.hi = true, 0, n-1
	} else {
		i.boundSlice = s
	}
	if n > g.tripLimit()*2 {
		g.counterLoop()
		return
	}
	s.used = true
	if g.chance(2) {
		g.line("for %s := 0; %s < len(%s); %s++ {", i.name, i.name, s.name, i.name)
	} else {
		g.line("for %s := len(%s) - 1; %s >= 0; %s-- {", i.name, s.name, i.name, i.name)
	}
	g.loopBody(n, i)
}

// shiftLoop runs while an unsigned value is non-zero, shifting it right.
func (g *gen) shiftLoop() {
	us := unsignedTypes()
	t := us[g.r.Intn(len(us))]
	k := 1 + g.r.Intn(4)
	trips := int64(t.bits/k + 1)
	if trips > g.tripLimit()*2 {
		g.counterLoop()
		return
	}
	u := &variable{name: g.name("u"), t: t, readonly: true, used: true}
	g.line("for %s := %s; %s != 0; {", u.name, typed(g.intExpr(t, 2, false), t), u.name)
	g.line("\t%s >>= %d", u.name, k)
	g.loopBody(trips, u)
}

// breakLoop has no condition and leaves through a break.
func (g *gen) breakLoop() {
	n := int64(g.r.Intn(int(g.tripLimit()) + 1))
	j := &variable{name: g.name("j"), t: tInt, readonly: true, used: true, hasRange: true, lo: 0, hi: max(n-1, 0)}
	g.line("for %s := 0; ; %s++ {", j.name, j.name)
	g.line("\tif %s >= %d {", j.name, n)
	g.line("\t\tbreak")
	g.line("\t}")
	g.loopBody(n, j)
}

// ----------------------------------------------------------------------------
// Calls and closures as statements

func (g *gen) callStmt() bool {
	var cands []*fnInfo
	for _, f := range g.funcs[:g.nfuncs] {
		if (f.pure || g.cx.writeGlobal) && g.cx.cost+g.cx.mult*(f.cost+1) <= g.cx.budget {
			cands = append(cands, f)
		}
	}
	if len(cands) == 0 {
		// Try a closure.
		t := g.randInt()
		c := g.call(t, false)
		if c == "" {
			return false
		}
		v := g.declare(&variable{name: g.name("v"), t: t})
		g.line("%s := %s", v.name, c)
		return true
	}
	f := cands[g.r.Intn(len(cands))]
	g.addCost(f.cost + 1)
	inst := g.instFor()
	call := g.callText(f, inst)
	var results []*typ
	for _, t := range f.results {
		results = append(results, g.subst(t, f.tparam, inst))
	}
	switch g.r.Intn(4) {
	case 0:
		g.line("%s", call)
	case 1:
		// Assign to existing variables where possible.
		var lhs []string
		for _, t := range results {
			var target *variable
			for _, v := range g.visible() {
				if v.t == t && g.canWriteRoot(v) && g.chance(2) {
					target = v
				}
			}
			if target == nil {
				lhs = append(lhs, "_")
			} else {
				lhs = append(lhs, target.name)
			}
		}
		g.line("%s = %s", strings.Join(lhs, ", "), call)
	default:
		var names []string
		var vars []*variable
		for _, t := range results {
			v := &variable{name: g.name("v"), t: t}
			names = append(names, v.name)
			vars = append(vars, v)
		}
		g.line("%s := %s", strings.Join(names, ", "), call)
		for _, v := range vars {
			g.declare(v)
		}
	}
	return true
}

func (g *gen) closure() {
	ci := &closureInfo{pure: g.chance(2)}
	if g.chance(5) {
		ci.result = tBool
	} else {
		ci.result = g.randInt()
	}
	name := g.name("c")
	outer := g.cx
	// A pure closure writes only its own variables; an impure one may
	// also write whatever the enclosing function may.
	inner := &ctx{
		level:         outer.level + 1,
		results:       []*typ{ci.result},
		minWriteLevel: outer.level + 1,
		writeGlobal:   !ci.pure && outer.writeGlobal,
		mult:          1,
		budget:        fnBudget / 4,
		tparam:        outer.tparam,
	}
	if !ci.pure {
		inner.minWriteLevel = outer.minWriteLevel
	}
	g.cx = inner
	g.push()
	var params []string
	for i, n := 0, g.r.Intn(3); i < n; i++ {
		t := g.randInt()
		v := g.declare(&variable{name: g.name("a"), t: t, used: true})
		ci.params = append(ci.params, t)
		params = append(params, v.name+" "+t.String())
	}
	g.line("%s := func(%s) %s {", name, strings.Join(params, ", "), ci.result)
	g.indent++
	g.stmts(1 + g.r.Intn(3))
	ret := g.returnValues()
	g.useAll()
	g.line("return %s", ret)
	g.sc = g.sc.parent
	g.indent--
	g.line("}")
	g.cx = outer
	ci.cost = inner.cost + 1
	v := g.declare(&variable{name: name, closure: ci})
	// Call it a few times.
	for i, n := 0, g.r.Intn(3); i < n; i++ {
		if g.cx.cost+g.cx.mult*(ci.cost+1) > g.cx.budget || (!ci.pure && len(g.ranged) > 0) {
			break
		}
		g.addCost(ci.cost + 1)
		v.used = true
		r := &variable{name: g.name("v"), t: ci.result}
		g.line("%s := %s(%s)", r.name, name, g.args(ci.params, make([]int, len(ci.params))))
		g.declare(r)
	}
}
