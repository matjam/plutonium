// special replaces qualified identifiers of Go packages with compat ones.
// fmt.Errorf and the errors functions need none: pluto/fmt and pluto/errors
// follow Go (language spec section 16), except errors.New at run time (see
// call).
var special = map[string]string{
	"fmt.Sprintf":     "compat.Sprintf",
	"fmt.Sprint":      "compat.Sprint",
	"fmt.Sprintln":    "compat.Sprintln",
	"strings.Builder": "compat.Builder",
	"strings.Join":    "compat.Join",
	"bytes.Buffer":    "compat.Buffer",
	// The library's Append functions append to a vec.Appender; the compat
	// forms keep Go's []byte destination, growing it as compat.Append does.
	"strconv.AppendInt":       "compat.AppendInt",
	"strconv.AppendFloat":     "compat.AppendFloat",
	"unicode/utf8.AppendRune": "compat.AppendRune",
	"fmt.Appendf":             "compat.Appendf",
	// Go's os name functions return the bytes the system gave as a string;
	// the library's return an error as well for bytes that are not valid
	// UTF-8, so the translation takes the display forms (language spec F.9).
	"os.Getenv":    "compat.Getenv",
	"os.LookupEnv": "compat.LookupEnv",
	"os.TempDir":   "compat.TempDir",
	// Go's os.Args, os.ReadFile and io.ReadAll return plain slices and
	// strings; the library's return owners (vec.Vec) or take accessors.
	"os.Args":     "compat.Args()",
	"os.ReadFile": "compat.ReadFile",
	"io.ReadAll":  "compat.ReadAll",
}

// syncStubs replace the locks and atomics of the compiler's own packages
// (internal/...), which run one task, with no-ops. The demos under testdata
// keep the real ones.
var syncStubs = map[string]string{
	"sync.Mutex":          "compat.Mutex",
	"sync.RWMutex":        "compat.RWMutex",
	"sync/atomic.Pointer": "compat.AtomicPointer",
}

// specialName returns the compat replacement of the Go name p.name (p an
// import path), if there is one.
func (t *translator) specialName(p, name string) (string, bool) {
	if r, ok := special[p+"."+name]; ok {
		return r, true
	}
	if strings.HasPrefix(t.goPath, goModule+"/internal/") {
		r, ok := syncStubs[p+"."+name]
		return r, ok
	}
	return "", false
}

